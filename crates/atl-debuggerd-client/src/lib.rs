//! libdebuggerd_client for AOSP code built against glibc: asking for another process's stack dump.
//! AOSP's client (`debuggerd/client/debuggerd_client.cpp`) first connects to tombstoned's intercept
//! socket, and only then signals the target (`SIGQUIT` for a Java dump, bionic's reserved
//! `BIONIC_SIGNAL_DEBUGGER` for a native one), whose in-process handler dumps through tombstoned. This
//! host has no tombstoned and no such handler, so every request ends where AOSP's ends when tombstoned
//! is unreachable: failure (`-1`), with no signal sent. Signalling anyway would be wrong here: bionic's
//! debugger signal number is glibc's `SIGRTMIN + 1`, free for an app to use.
//!
//! A separate crate, not part of atl-bionic: the debuggerd client is not bionic API (system/core), and
//! is its own module with its own shared object, as in AOSP. Boundary crate: `unsafe` only in `ffi`.
#![deny(unsafe_code)]

/// Generated by build.rs from AOSP's pinned header.
mod generated {
    pub mod client {
        include!(concat!(env!("OUT_DIR"), "/client.rs"));
    }
}

#[allow(unsafe_code)]
mod ffi;
