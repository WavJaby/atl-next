/// A libandroid lookup or an ALooper call failed; the text names which.
#[derive(Debug, thiserror::Error)]
#[error("{0}")]
pub struct LooperError(String);

fn dl_error() -> String {
    // SAFETY: no arguments; the result is null or a NUL-terminated string valid until the next dl call on this thread, copied at once
    let e = unsafe { libc::dlerror() };
    if e.is_null() {
        "(no dlerror)".to_owned()
    } else {
        // SAFETY: non-null: a NUL-terminated string (above)
        unsafe { CStr::from_ptr(e) }.to_string_lossy().into_owned()
    }
}

/// `name` in `handle` as fn type `F`.
///
/// # Safety
/// `handle` is live and `F` is the pointer type of the function of that name.
unsafe fn sym<F: Copy>(handle: *mut c_void, name: &CStr) -> Result<F, LooperError> {
    const {
        assert!(size_of::<F>() == size_of::<*mut c_void>());
    }
    // SAFETY: a live handle and a NUL-terminated name (caller)
    let p = unsafe { libc::dlsym(handle, name.as_ptr()) };
    if p.is_null() {
        return Err(LooperError(format!(
            "{}: {}",
            name.to_string_lossy(),
            dl_error()
        )));
    }
    // SAFETY: a function's address, F its pointer type of the same size (caller, asserted above)
    Ok(unsafe { std::mem::transmute_copy::<*mut c_void, F>(&p) })
}

/// libandroid by soname: found on the runtime library path, as libandroid_runtime is.
const ANDROID: &CStr = c"libandroid.so";

/// libandroid's Looper functions, resolved once per [`load`](LooperApi::load).
pub struct LooperApi {
    prepare: looper::ALooper_prepare,
    for_thread: looper::ALooper_forThread,
    add_fd: looper::ALooper_addFd,
    remove_fd: looper::ALooper_removeFd,
    poll_once: looper::ALooper_pollOnce,
}

impl LooperApi {
    /// Loads libandroid (`RTLD_NOW | RTLD_LOCAL`) and resolves the functions from its handle; the handle is never closed. libandroid_runtime does not link libandroid, so its handle cannot resolve these.
    pub fn load() -> Result<Self, LooperError> {
        // SAFETY: a NUL-terminated soname and libc's flag values
        let h = unsafe { libc::dlopen(ANDROID.as_ptr(), libc::RTLD_NOW | libc::RTLD_LOCAL) };
        if h.is_null() {
            return Err(LooperError(format!("loading libandroid: {}", dl_error())));
        }
        // SAFETY: each F is the generated type of the function of that name; h is live
        unsafe {
            Ok(LooperApi {
                prepare: sym(h, c"ALooper_prepare")?,
                for_thread: sym(h, c"ALooper_forThread")?,
                add_fd: sym(h, c"ALooper_addFd")?,
                remove_fd: sym(h, c"ALooper_removeFd")?,
                poll_once: sym(h, c"ALooper_pollOnce")?,
            })
        }
    }

    /// The calling thread's Looper (`ALooper_prepare`, non-callback fds allowed). Called before Java's MessageQueue exists, so NativeMessageQueue adopts it (`Looper::getForThread`).
    pub fn prepare_looper(&self) -> Result<Looper, LooperError> {
        let flags = looper::ALOOPER_PREPARE_ALLOW_NON_CALLBACKS as c_int;
        // SAFETY: the header's flag value; the returned Looper belongs to this thread (libutils keeps it for the thread's life)
        let ptr = unsafe { (self.prepare)(flags) };
        if ptr.is_null() {
            return Err(LooperError("ALooper_prepare returned no Looper".to_owned()));
        }
        Ok(self.looper(ptr.cast()))
    }

    /// The calling thread's existing Looper (`ALooper_forThread`), None on a thread without one. For a Java Looper thread (Looper.prepare made it, NativeMessageQueue adopted it): `prepare_looper`
    /// there would ask for non-callback fds the Java Looper was made without, which libutils logs as a mismatch.
    pub fn thread_looper(&self) -> Option<Looper> {
        // SAFETY: no arguments; the Looper returned (no reference taken) belongs to this thread, which libutils keeps alive for the thread's life
        let ptr = unsafe { (self.for_thread)() };
        (!ptr.is_null()).then(|| self.looper(ptr.cast()))
    }

    fn looper(&self, ptr: *mut c_void) -> Looper {
        Looper {
            ptr,
            add_fd: self.add_fd,
            remove_fd: self.remove_fd,
            poll_once: self.poll_once,
        }
    }
}

/// The callback `ALooper_addFd` takes (looper.h's `ALooper_callbackFunc`, which the generator does not emit as a typedef).
pub type Callback = Option<unsafe extern "C" fn(c_int, c_int, *mut c_void) -> c_int>;

/// A thread's Looper. Thread-bound: only the thread that prepared it registers on it or polls it.
#[derive(Clone, Copy)]
pub struct Looper {
    ptr: *mut c_void,
    add_fd: looper::ALooper_addFd,
    remove_fd: looper::ALooper_removeFd,
    poll_once: looper::ALooper_pollOnce,
}

impl Looper {
    /// `ALooper_addFd` with a callback: `callback(fd, events, data)` runs on this thread inside the Looper's poll and returns 1 to stay registered.
    ///
    /// # Safety
    /// `callback` may dereference `data`: it stays valid until `remove_fd` of `fd` and past the poll batch that removal ends.
    pub unsafe fn add_fd(
        &self,
        fd: RawFd,
        events: c_int,
        callback: Callback,
        data: *mut c_void,
    ) -> Result<(), LooperError> {
        // SAFETY: this thread's live Looper; the callback and `data` are the caller's (contract above)
        let rc = unsafe {
            (self.add_fd)(
                self.ptr.cast(),
                fd,
                looper::ALOOPER_POLL_CALLBACK as c_int,
                events,
                callback,
                data,
            )
        };
        if rc != 1 {
            return Err(LooperError(format!("ALooper_addFd({fd}) returned {rc}")));
        }
        Ok(())
    }

    /// `ALooper_removeFd`: 1 when the fd was registered, 0 when it was not (both fine here).
    pub fn remove_fd(&self, fd: RawFd) -> Result<(), LooperError> {
        // SAFETY: this thread's live Looper; removing an unregistered fd is a no-op
        let rc = unsafe { (self.remove_fd)(self.ptr.cast(), fd) };
        if rc != 0 && rc != 1 {
            return Err(LooperError(format!("ALooper_removeFd({fd}) returned {rc}")));
        }
        Ok(())
    }

    /// `ALooper_pollOnce(timeout_ms)` with no out-parameters: runs the callbacks of the fds ready within the timeout, as Java's MessageQueue does once Java runs. Its result is not needed: the caller checks its own condition.
    pub fn poll_once(&self, timeout_ms: c_int) {
        // SAFETY: this thread's live Looper; null out-parameters are allowed (looper.h)
        unsafe {
            (self.poll_once)(
                timeout_ms,
                std::ptr::null_mut(),
                std::ptr::null_mut(),
                std::ptr::null_mut(),
            )
        };
    }
}

/// One posted closure.
type Task = Box<dyn FnOnce() + Send>;

/// Posts dropped because their Looper's thread had ended, process-wide.
static DROPPED: AtomicU64 = AtomicU64::new(0);

/// Counts `n` dropped posts; logs at the first and each power of two.
fn count_dropped(n: u64) {
    for _ in 0..n {
        let total = DROPPED.fetch_add(1, Ordering::Relaxed) + 1;
        if total.is_power_of_two() {
            tracing::warn!("looper: post to quit looper {total}");
        }
    }
}

#[derive(Default)]
struct Queue {
    tasks: VecDeque<Task>,
    /// The target thread ended: nothing will drain the queue again.
    quit: bool,
}

/// What a [`Poster`]'s clones and its Looper registration share.
struct Shared {
    queue: Mutex<Queue>,
    /// Written once per post; the Looper's registration, drained by [`drain`].
    wake: OwnedFd,
}

impl Shared {
    fn new() -> Result<Self, LooperError> {
        let wake = eventfd(0, EventfdFlags::CLOEXEC | EventfdFlags::NONBLOCK)
            .map_err(|e| LooperError(format!("eventfd: {e}")))?;
        Ok(Shared {
            queue: Mutex::new(Queue::default()),
            wake,
        })
    }

    fn lock(&self) -> MutexGuard<'_, Queue> {
        // a poisoned queue is still a queue: a task panicking aborts (it runs in an extern "C" callback), so poison cannot leave it half-edited
        self.queue.lock().unwrap_or_else(|p| p.into_inner())
    }

    fn post(&self, f: Task) {
        let mut q = self.lock();
        if q.quit {
            drop(q);
            drop(f);
            count_dropped(1);
            return;
        }
        q.tasks.push_back(f);
        drop(q);
        // a full counter (2^64 - 2 unread posts) cannot happen: the drain reads it on every pass
        let _ = rustix::io::write(&self.wake, &1u64.to_ne_bytes());
    }

    /// Runs the tasks queued when it began, in order; later posts wrote the eventfd again, so they run in the next pass (a task that posts cannot starve the Looper).
    fn drain(&self) {
        let mut counter = [0u8; 8];
        let _ = rustix::io::read(&self.wake, &mut counter);
        let batch = self.lock().tasks.len();
        for _ in 0..batch {
            let Some(task) = self.lock().tasks.pop_front() else {
                break;
            };
            task();
        }
    }

    fn quit(&self) {
        let dropped = {
            let mut q = self.lock();
            q.quit = true;
            std::mem::take(&mut q.tasks)
        };
        let n = dropped.len() as u64;
        drop(dropped);
        count_dropped(n);
    }
}

/// The Posters attached on this thread: marked quit when the thread ends, after which its Looper polls no more.
#[derive(Default)]
struct Attached(RefCell<Vec<Arc<Shared>>>);

impl Drop for Attached {
    fn drop(&mut self) {
        for shared in self.0.take() {
            shared.quit();
        }
    }
}

thread_local! {
    static ATTACHED: Attached = Attached::default();
}

/// The `post` executor: runs closures on one Looper's thread, posted from any thread, in post order, each inside that Looper's poll (an fd callback, the class of the InputChannel's). Clones post to the same Looper.
/// Posts after that thread ended are dropped unrun and counted (`looper: post to quit looper <n>`).
#[derive(Clone)]
pub struct Poster(Arc<Shared>);

impl Poster {
    /// Registers a new executor with `looper`, which must be the calling thread's Looper; its registration lives as long as the thread.
    pub fn attach(looper: &Looper) -> Result<Poster, LooperError> {
        let shared = Arc::new(Shared::new()?);
        // the registration's reference: leaked, so a callback batched before the thread ends still reads valid memory
        let data = Arc::into_raw(Arc::clone(&shared))
            .cast_mut()
            .cast::<c_void>();
        // SAFETY: `data` is a leaked Arc reference, valid for the process; `on_wake` reads it as `Shared`
        let added = unsafe {
            looper.add_fd(
                shared.wake.as_fd().as_raw_fd(),
                events::INPUT,
                Some(on_wake),
                data,
            )
        };
        if let Err(e) = added {
            // SAFETY: the reference `into_raw` made above; the Looper refused it, so nothing else holds it
            drop(unsafe { Arc::from_raw(data.cast_const().cast::<Shared>()) });
            return Err(e);
        }
        ATTACHED.with(|a| a.0.borrow_mut().push(Arc::clone(&shared)));
        Ok(Poster(shared))
    }

    /// Queues `f` to run on the Looper's thread after every earlier post.
    pub fn post(&self, f: Box<dyn FnOnce() + Send>) {
        self.0.post(f);
    }
}

/// The eventfd's Looper callback: runs the batch and stays registered.
unsafe extern "C" fn on_wake(_fd: c_int, _events: c_int, data: *mut c_void) -> c_int {
    // SAFETY: `data` is the leaked Arc<Shared> reference `Poster::attach` registered, valid for the process
    let shared = unsafe { &*data.cast_const().cast::<Shared>() };
    shared.drain();
    1
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::mpsc::channel;

    /// Posts from another thread run on the draining thread, in post order, only when drained.
    #[test]
    fn posts_run_in_order_on_the_draining_thread() {
        let shared = Arc::new(Shared::new().expect("eventfd"));
        let poster = Poster(Arc::clone(&shared));
        let (tx, rx) = channel();
        let here = std::thread::current().id();
        std::thread::spawn(move || {
            for i in 0..3 {
                let tx = tx.clone();
                poster.post(Box::new(move || {
                    let _ = tx.send((i, std::thread::current().id()));
                }));
            }
        })
        .join()
        .expect("poster thread");
        assert!(rx.try_recv().is_err(), "nothing runs before the drain");
        shared.drain();
        let got: Vec<_> = rx.try_iter().collect();
        assert_eq!(got, vec![(0, here), (1, here), (2, here)]);
    }

    /// A task posted while draining waits for the next drain (the batch is fixed when the drain begins).
    #[test]
    fn a_post_from_a_task_runs_next_pass() {
        let shared = Arc::new(Shared::new().expect("eventfd"));
        let (tx, rx) = channel();
        let inner = Arc::clone(&shared);
        shared.post(Box::new(move || {
            let tx2 = tx.clone();
            inner.post(Box::new(move || {
                let _ = tx2.send(2);
            }));
            let _ = tx.send(1);
        }));
        shared.drain();
        assert_eq!(rx.try_iter().collect::<Vec<_>>(), vec![1]);
        shared.drain();
        assert_eq!(rx.try_iter().collect::<Vec<_>>(), vec![2]);
    }

    /// After the target thread ended, a queued post and a new one are both dropped unrun, each counted.
    #[test]
    fn posts_after_quit_are_dropped_and_counted() {
        let shared = Arc::new(Shared::new().expect("eventfd"));
        let (tx, rx) = channel::<u32>();
        let tx2 = tx.clone();
        shared.post(Box::new(move || {
            let _ = tx.send(1);
        }));
        let before = DROPPED.load(Ordering::Relaxed);
        shared.quit();
        shared.post(Box::new(move || {
            let _ = tx2.send(2);
        }));
        shared.drain();
        assert!(rx.try_recv().is_err());
        // other tests in this binary never quit, so the delta is this test's: the queued post and the late one
        assert_eq!(DROPPED.load(Ordering::Relaxed) - before, 2);
    }
}
