//! libandroid's Looper API (NDK looper.h) as the process's own code calls it ([`LooperApi`], [`Looper`]), and the `post` executor over it ([`Poster`], display-thread plan D2): a closure posted from any thread runs on one Looper's thread inside that Looper's poll, in post order.
//! libandroid is the converter's output, so it is dlopened (`RTLD_NOW | RTLD_LOCAL`) and each function resolved by name; its fn types come from looper.h (build.rs).
//! `unsafe` only at the C boundary: the dlopen/dlsym lookups, the ALooper calls, and the fd callback that drains a [`Poster`].

