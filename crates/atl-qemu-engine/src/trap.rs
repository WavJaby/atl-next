//! P1's hook (patches/qemu 0001): QEMU's aarch64 `cpu_loop` calls `atl_svc_hook(env, imm16)` on every `svc`; this strong definition replaces the patch's weak default.
//! Answer: 0 handled (resume at pc, already past the svc), 1 leave this `cpu_loop` (a guest call returned), <0 not ours (QEMU's syscall path).
//! Immediates: Linux ignores the svc immediate and bionic uses `svc #0`, so nonzero values in the 0x7a1x range are ours, and so is any immediate with bit 15 ([`BIND`]: a binding thunk, id = the low 15 bits). The guest fixture (xtask-harness/testdata/qemu-spike/fixture.c) repeats them.

use std::cell::Cell;
use std::ffi::{c_int, c_void};

use crate::engine::{Guest, Trap, lib};
use crate::thunk::BIND;

/// Host call: the callback's answer lands in x0.
pub const CALL: u32 = 0x7a10;
/// Return stub: a guest call ([`Guest::call`]) is finished, leave the innermost `cpu_loop`.
pub const RET: u32 = 0x7a11;
/// Report a value (x0) for a gate.
pub const REPORT: u32 = 0x7a12;
/// Bootstrap: x0 = payload, x1 = the guest's `svc #RET` stub. Installs the fault chain, runs the callback, hands its answer to [`crate::start`] and parks the boot thread for good: the guest never resumes after it.
pub const BOOT: u32 = 0x7a13;
/// A guest-created thread's first instruction (the guest's own `clone`): registers the thread for fault classification ([`crate::signal::register_thread`]). Answer: none.
pub const THREAD: u32 = 0x7a14;
/// Bit 15 of the immediate ([`BIND`], generated by atl-bridgegen): a binding thunk. Answer: the host callback's, in x0.
/// The bit the decode tests. Break `bind-decode` (gate l) tests bit 14 instead, so bind thunks fall through to QEMU's syscall path.
#[cfg(not(atl_qe_bind_decode))]
const BIND_TEST: u32 = BIND;
#[cfg(atl_qe_bind_decode)]
const BIND_TEST: u32 = 0x4000;

const HANDLED: c_int = 0;
const LEAVE: c_int = 1;
const NOT_OURS: c_int = -1;

thread_local! {
    /// CALL / BIND traps running on this thread (nested through guest calls from their callbacks).
    static DEPTH: Cell<u32> = const { Cell::new(0) };
    /// [`end_call`] ran inside the innermost running trap: its return leaves the `cpu_loop` of the guest call it interrupted.
    static END: Cell<bool> = const { Cell::new(false) };
}

/// ABI `end_call`: the innermost CALL / BIND trap running on this thread, when it returns, ends the guest call it interrupted with its answer (x0), instead of resuming the guest after the svc. False when no such trap runs.
pub(crate) fn end_call() -> bool {
    if DEPTH.with(Cell::get) == 0 {
        return false;
    }
    END.with(|e| e.set(true));
    true
}

/// A CALL / BIND trap: the callback's answer in x0, then resume past the svc, or leave this `cpu_loop` when the callback asked [`end_call`]. An outer trap's pending request is kept aside while this one runs.
fn host_trap(g: Guest, t: Trap) -> c_int {
    let outer = END.with(|e| e.replace(false));
    DEPTH.with(|d| d.set(d.get() + 1));
    let r = (lib().on_trap)(g, t);
    DEPTH.with(|d| d.set(d.get() - 1));
    // break `ret-reg` (gate a): the answer arrives corrupted
    #[cfg(atl_qe_ret_reg)]
    let r = r ^ 1;
    g.set_x(0, r);
    if END.with(|e| e.replace(outer)) {
        LEAVE
    } else {
        HANDLED
    }
}

/// # Safety
/// Called by QEMU's `cpu_loop` only: `env` is the calling thread's live `CPUArchState`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn atl_svc_hook(env: *mut c_void, imm: u32) -> c_int {
    // a panic must not unwind into QEMU's C frames
    match std::panic::catch_unwind(|| dispatch(Guest::new(env), imm)) {
        Ok(r) => r,
        Err(_) => std::process::abort(),
    }
}

fn dispatch(g: Guest, imm: u32) -> c_int {
    let on_trap = lib().on_trap;
    match imm {
        RET => LEAVE,
        BOOT => crate::engine::boot(g),
        CALL => host_trap(g, Trap::Call(std::array::from_fn(|i| g.x(i)))),
        REPORT => {
            on_trap(g, Trap::Report(g.x(0)));
            HANDLED
        }
        THREAD => {
            crate::signal::register_thread();
            HANDLED
        }
        _ if imm & BIND_TEST != 0 => host_trap(
            g,
            Trap::Bind {
                id: imm & !BIND,
                args: std::array::from_fn(|i| g.x(i)),
            },
        ),
        _ => NOT_OURS,
    }
}
