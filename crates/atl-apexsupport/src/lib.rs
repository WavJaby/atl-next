//! libapexsupport for AOSP code built against glibc: loading a library from an APEX, e.g. libbinder's
//! `openDeclaredPassthroughHal` for a HAL updatable via an APEX. As AOSP's (`apexsupport.cpp`): the APEX
//! name with `.` -> `_` is the exported linker namespace, and the library is `android_dlopen_ext`ed in it;
//! null when the namespace is not exported or the library does not load. Both calls go to libc's
//! provider, atl-bionic, whose `linker` is the one place namespaced loads go: there one namespace now,
//! exporting every name, so a load finds what `dlopen` finds -- this host installs no APEX, so a HAL
//! library is not found and the result is null, as on a device without that APEX. AOSP's failure logs
//! are left out: the error stays in `dlerror` for the caller.
//!
//! A separate crate, not part of atl-bionic or atl-vndksupport: libapexsupport is its own module with
//! its own shared object and API (system/apex), as in AOSP; like atl-vndksupport it is a shell over the
//! one namespaced-load concept in atl-bionic, reached only through its C ABI. Boundary crate: `unsafe`
//! only in `ffi`.
#![deny(unsafe_code)]

/// Generated by build.rs from AOSP's pinned sources: the exports' header, and the bionic API imported.
mod generated {
    pub mod apexsupport {
        include!(concat!(env!("OUT_DIR"), "/apexsupport.rs"));
    }
    pub mod dlext {
        include!(concat!(env!("OUT_DIR"), "/dlext.rs"));
    }
    pub mod libdl_android {
        include!(concat!(env!("OUT_DIR"), "/libdl_android.rs"));
    }
}

#[allow(unsafe_code)]
mod ffi;

/// AOSP's namespace name of an APEX: `.` -> `_` (`com.android.foo` -> `com_android_foo`).
pub fn namespace_name(apex: &[u8]) -> Vec<u8> {
    apex.iter()
        .map(|&b| if b == b'.' { b'_' } else { b })
        .collect()
}

#[cfg(test)]
mod tests {
    /// apexsupport.cpp: std::replace(namespaceName.begin(), namespaceName.end(), '.', '_').
    #[test]
    fn namespace_name_replaces_dots() {
        assert_eq!(
            super::namespace_name(b"com.android.hardware.foo"),
            b"com_android_hardware_foo"
        );
        assert_eq!(super::namespace_name(b""), b"");
    }
}
