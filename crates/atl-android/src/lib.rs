//! The NDK's libandroid, ATL's own (plan: "our NDK in Rust"): one implementation serving apps and the AOSP framework code built here (providers.toml row `libandroid`).
//! Exports are added per consumer; each is declared by the NDK's pinned header, listed in `libandroid.map.txt` and signature-checked (build.rs).
//!
//! - System fonts (`fonts`): `ASystemFontIterator_*`, `AFont_*` (API 29), which Skia's NDK font manager calls in libhwui.
//!
//! Boundary crate: `unsafe` only in `ffi`, whose entry points convert pointers and call the safe modules.
#![deny(unsafe_code)]

pub mod fonts;

/// Generated by build.rs from the NDK's pinned headers: each export's signature check and the opaque types.
mod generated {
    pub mod font {
        include!(concat!(env!("OUT_DIR"), "/font.rs"));
    }
    pub mod system_fonts {
        include!(concat!(env!("OUT_DIR"), "/system_fonts.rs"));
    }
}

#[allow(unsafe_code)]
mod ffi;
