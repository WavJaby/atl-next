//! libbinder_driver for binderd: libbinder's binder driver I/O (`BinderDriver.h`, patches/aosp/frameworks/native 0003) over binderd's socket protocol (`atl_binder_wire::proto`), instead of the kernel's `/dev/binder` (providers.toml `libbinder_driver`).
//!
//! - `binder_driver_open("/dev/binder")`: the process's control connection, inherited as fd `ATL_BINDER_FD`, is handshaken once; each open returns a dup of it. Other paths (`/dev/vndbinder`, `/dev/hwbinder`): ENOENT.
//! - `binder_driver_mmap`: an anonymous region local to the process; binderd learns its size and alone allocates offsets in it.
//! - `binder_driver_ioctl`: `BINDER_WRITE_READ` on the calling thread's connection (made on first use over control, closed by `BINDER_THREAD_EXIT` or at thread exit), one request/reply per call; per-process ioctls over control; any other is sent as `Unsupported` for binderd to count, and fails EINVAL.
//! - `binder_driver_poll_fd`: the calling thread's connection, switched to poll mode.
//!
//! Boundary crate: `unsafe` only in `exports` (the C ABI shells) and `region` (the mapped memory); `process` is safe.
#![deny(unsafe_code)]

#[allow(unsafe_code)]
mod exports;
mod process;
#[allow(unsafe_code)]
mod region;

