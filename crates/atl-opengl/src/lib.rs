//! AOSP's `frameworks/native/opengl/libs` surface (libEGL, libGLES*) that AOSP code links against, on the host's GL loaders (providers.toml rows `libEGL`, `libGLESv1_CM`, `libGLESv2`, `libGLESv3`); linked next to the host library, never in its place.
//!
//! Extension entry points (`ffi`): AOSP's libEGL exports every extension function it knows; the host's (libglvnd) exports only the core API and hands out extensions through `eglGetProcAddress`, so AOSP code calling `eglCreateImageKHR`, `glEGLImageTargetTexture2DOES`, ... directly links against nothing.
//! Here each extension function of AOSP's pinned Khronos headers is a shell (generated by build.rs) that looks its implementation up with `eglGetProcAddress` on first call and forwards to it, arguments and result unchanged.
//! The lookup is per process: EGL 1.5 §3.10 makes the returned pointers context-independent, valid for every display and context.
//! No core function is defined, so lookups of the host's own symbols are unaffected.
//!
//! libEGL's private API (`private`): the two `namespace android` functions framework code calls (`egl_set_cache_filename`, `egl_get_init_count`), with the headers declaring them (build.rs), and hwui's systrace frame marker `eglBeginFrame` (no-op; no header declares it).
//!
//! Boundary crate: `unsafe` only in `ffi` and `private`.
#![deny(unsafe_code)]

#[allow(unsafe_code)]
mod ffi;
#[allow(unsafe_code)]
mod private;

/// Generated by build.rs from AOSP's pinned private EGL headers: each export's signature check.
mod generated {
    pub mod cache {
        include!(concat!(env!("OUT_DIR"), "/cache.rs"));
    }
    pub mod display {
        include!(concat!(env!("OUT_DIR"), "/display.rs"));
    }
}
