//! atl-app-launcher: starts an app process's runtime -- the one launch path (the broker will run it inside the sandbox; xtask and test harnesses run it now).
//! dalvikvm's start (art/dalvikvm/dalvikvm.cc) through the standard seams only: the JNI invocation API, liblog's logger API, bionic's API. Steps:
//! 1. refuse to start without a property area: bionic's `__system_properties_init` maps `$ATL_PROP_AREA` (atl-bionic `AREA_ENV`), else `/dev/__properties__`; without it every property reads unset and the runtime runs on defaults no Android process sees.
//! 2. `JNI_CreateJavaVM` through libnativehelper's JniInvocation, the VM options as dalvikvm takes them (`args`).
//! 3. our logger via `__android_log_set_logger`, after the VM exists: ART's InitLogging (ART_TARGET_LINUX) installs libbase's StderrLogger through the same call (system/libbase/logging.cpp SetLogger), replacing any earlier one. The logger turns each message into a C6 record (`log`); liblog filters before calling it.
//! 4. `android_set_application_target_sdk_version` (bionic's compat checks); ART calls it from VMRuntime.setTargetSdkVersion only under ART_TARGET_ANDROID.
//! 5. `main(String[])` of the class, then detach + DestroyJavaVM and `_exit` with dalvikvm's status.
//!
//! The library holds all of it; the executable (`src/main.rs`, feature `sigchain`) only calls [`main`]. It needs a link no plain cargo build can make: DT_NEEDED on the converter's libsigchain ahead of libc, as the converter links dalvikvm's device variant,
//! so `sigaction` / `signal` of every library loaded later bind to libsigchain and a game engine's or crash reporter's own SIGSEGV handler is chained behind ART's fault handler instead of replacing it. `xtask native` builds it (build.rs says how).
//! Boundary crate (JNI, `dlopen`): `unsafe` only in `ffi`.
#![deny(unsafe_code)]

mod args;
#[allow(unsafe_code)]
mod ffi;
mod log;

/// Generated by build.rs from the headers that declare what the launcher calls.
#[allow(
    dead_code,
    non_upper_case_globals,
    non_snake_case,
    non_camel_case_types
)]
mod generated {
    pub mod dlfcn {
        include!(concat!(env!("OUT_DIR"), "/dlfcn.rs"));
    }
    pub mod unistd {
        include!(concat!(env!("OUT_DIR"), "/unistd.rs"));
    }
    pub mod jni {
        include!(concat!(env!("OUT_DIR"), "/jni.rs"));
    }
    pub mod jni_invocation {
        include!(concat!(env!("OUT_DIR"), "/jni_invocation.rs"));
    }
    pub mod log {
        include!(concat!(env!("OUT_DIR"), "/log.rs"));
    }
    pub mod system_properties {
        include!(concat!(env!("OUT_DIR"), "/system_properties.rs"));
    }
    pub mod libdl_android {
        include!(concat!(env!("OUT_DIR"), "/libdl_android.rs"));
    }
}

use anyhow::{Result, anyhow, bail};

fn run() -> Result<i32> {
    let launch = args::parse(std::env::args_os()).map_err(|e| anyhow!(e))?;
    let rt = ffi::Runtime::load()?;
    if !rt.has_property_area() {
        bail!(
            "no system property area: neither ${} nor /dev/__properties__ is a bionic property area (the broker or the harness writes one; atl-property-service)",
            atl_bionic::AREA_ENV
        );
    }
    let vm = rt.create_vm(&launch.vm_options)?;
    rt.install_logger();
    rt.set_target_sdk(launch.target_sdk);
    let Some(class) = &launch.class else {
        bail!("Class name required");
    };
    let rc = vm.run_main(class, &launch.args);
    vm.shut_down()?;
    Ok(rc)
}

/// The launcher's whole run, from the process's arguments to `_exit`.
pub fn main() -> ! {
    let status = match run() {
        Ok(rc) => rc,
        Err(e) => {
            use std::io::Write;
            let _ = writeln!(std::io::stderr(), "atl-app-launcher: {e:#}");
            1
        }
    };
    ffi::fast_exit(status)
}
