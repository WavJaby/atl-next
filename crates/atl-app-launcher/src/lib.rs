use anyhow::{Result, anyhow, bail};
use atl_platform_ui::Ui;

/// The compositor's threads: attached to the VM, as a binder thread is.
#[cfg(feature = "converter")]
struct AttachedThreads(ffi::VmHandle);

#[cfg(feature = "converter")]
impl atl_composer::ThreadHost for AttachedThreads {
    fn spawn(&self, name: &str, f: Box<dyn FnOnce() + Send>) -> std::io::Result<()> {
        self.0.spawn_attached(name, f)
    }
}

/// Step 5b'. The compositor lives as long as the process (its clock or deliver thread holds it); a start that fails is reported and the app starts without one, and waits at its first libgui call.
/// `ui`: UI mode's toolkit (step 5b''), whose window the compositor shows.
#[cfg(feature = "converter")]
fn start_compositor(vm: &ffi::Vm, ui: Option<atl_platform_ui::PlatformUi>) {
    use std::io::Write;
    if let Err(e) = atl_composer::start(&AttachedThreads(vm.handle()), ui) {
        let _ = writeln!(std::io::stderr(), "atl-app-launcher: no compositor: {e}");
    }
}

/// Without the converter's libraries there is no binder to serve it with.
#[cfg(not(feature = "converter"))]
fn start_compositor(_vm: &ffi::Vm, _ui: Option<atl_platform_ui::PlatformUi>) {}

/// Step 5b''. UI mode (`ro.atl.ui=gtk`, atld `--ui gtk`): the main thread's Looper is made before Java (its MessageQueue adopts it), then GTK starts on this thread with its GLib main context mirrored
/// into the Looper (atl-platform-ui-linux `mirror`, over the `looper` seam), so GTK runs while the app's main thread idles in its Looper and a blocked one answers no ping.
fn start_ui() -> Result<atl_platform_ui::PlatformUi> {
    let thread_looper = ffi::LooperApi::load()?.prepare_looper()?;
    atl_platform_ui::PlatformUi::attach(Box::new(looper::AndroidLooper::new(thread_looper)))
        .map_err(|e| anyhow!("{e}"))
}

/// AndroidRuntime::startVm's NativeBridge option from `ro.dalvik.vm.native.bridge` (unset, empty or "0": none), plus `-Xforce-nb-testing`: a non-zygote ART unloads the bridge unless forced
/// (runtime.cc `InitNonZygoteOrPostFork` action kUnload), and our app processes are not zygote forks; bridge 1 runs same-ISA bionic code through it (bridge-1 plan section 2, R4).
fn native_bridge_options(property: Option<String>) -> Vec<std::ffi::CString> {
    match property {
        Some(lib) if !lib.is_empty() && lib != "0" => [
            format!("-XX:NativeBridge={lib}"),
            "-Xforce-nb-testing".to_owned(),
        ]
        .into_iter()
        .filter_map(|o| std::ffi::CString::new(o).ok())
        .collect(),
        _ => Vec::new(),
    }
}

fn run() -> Result<i32> {
    let launch = args::parse(std::env::args_os()).map_err(|e| anyhow!(e))?;
    ffi::install_signal_stack()?;
    ffi::install_crash_handler()?;
    let rt = ffi::Runtime::load()?;
    if !rt.has_property_area() {
        bail!(
            "no system property area: neither ${} nor /dev/__properties__ is a bionic property area (the broker or the harness writes one; atl-property-service)",
            atl_bionic::AREA_ENV
        );
    }
    let mut vm_options = launch.vm_options.clone();
    if launch.app {
        vm_options.extend(native_bridge_options(
            rt.property(c"ro.dalvik.vm.native.bridge"),
        ));
    }
    let vm = rt.create_vm(&vm_options)?;
    rt.install_logger();
    rt.set_target_sdk(launch.target_sdk);
    let Some(class) = &launch.class else {
        bail!("Class name required");
    };
    let rc = if launch.app {
        let android = ffi::AndroidRuntime::load()?;
        android.attach(&vm)?;
        android.start_thread_pool();
        let ui = if rt.property(c"ro.atl.ui").as_deref() == Some("gtk") {
            start_ui()
                .inspect_err(|e| {
                    use std::io::Write;
                    let _ = writeln!(std::io::stderr(), "atl-app-launcher: no UI mode: {e:#}");
                })
                .ok()
        } else {
            None
        };
        start_compositor(&vm, ui);
        vm.run_zygote_init(launch.target_sdk, class, &launch.args)
    } else {
        vm.run_main(class, &launch.args)
    };
    vm.shut_down()?;
    Ok(rc)
}

/// The launcher's whole run, from the process's arguments to `_exit`.
pub fn main() -> ! {
    trace::install();
    let status = match run() {
        Ok(rc) => rc,
        Err(e) => {
            use std::io::Write;
            let _ = writeln!(std::io::stderr(), "atl-app-launcher: {e:#}");
            1
        }
    };
    ffi::fast_exit(status)
}

#[cfg(test)]
mod nb_tests {
    use super::native_bridge_options;

    #[test]
    fn native_bridge_option_follows_the_property() {
        let o = native_bridge_options(Some("libx.so".into()));
        assert_eq!(
            o,
            [
                c"-XX:NativeBridge=libx.so".to_owned(),
                c"-Xforce-nb-testing".to_owned()
            ]
        );
        assert!(native_bridge_options(Some("0".into())).is_empty());
        assert!(native_bridge_options(Some(String::new())).is_empty());
        assert!(native_bridge_options(None).is_empty());
    }
}
