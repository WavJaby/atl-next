use std::path::Path;

use anyhow::{Context as _, Result, anyhow, bail};
use atl_platform_ui::Ui;

/// The compositor's threads: attached to the VM, as a binder thread is.
#[cfg(feature = "converter")]
struct AttachedThreads(ffi::VmHandle);

#[cfg(feature = "converter")]
impl atl_composer::ThreadHost for AttachedThreads {
    fn spawn(&self, name: &str, f: Box<dyn FnOnce() + Send>) -> std::io::Result<()> {
        self.0.spawn_attached(name, f)
    }
}

/// Step 5b'. The compositor lives as long as the process (its clock or deliver thread holds it); a start that fails is reported and the app starts without one, and waits at its first libgui call.
/// `ui`: UI mode's toolkit (step 5b''), whose window the compositor shows.
#[cfg(feature = "converter")]
fn start_compositor(vm: &ffi::Vm, ui: Option<atl_platform_ui::PlatformUi>) {
    use std::io::Write;
    if let Err(e) = atl_composer::start(&AttachedThreads(vm.handle()), ui) {
        let _ = writeln!(std::io::stderr(), "atl-app-launcher: no compositor: {e}");
    }
}

/// Without the converter's libraries there is no binder to serve it with.
#[cfg(not(feature = "converter"))]
fn start_compositor(_vm: &ffi::Vm, _ui: Option<atl_platform_ui::PlatformUi>) {}

/// Step 1b. The process's view of servicemanager (atl-service-view), before `JNI_CreateJavaVM`: nothing has called libbinder's `defaultServiceManager()` yet (the launcher reaches libbinder only from step 5b on),
/// and libbinder aborts if the view comes after it. Every process gets it; one that never asks for a service never opens the driver.
#[cfg(feature = "converter")]
fn install_service_view() -> Result<()> {
    atl_service_view::install().map_err(|e| anyhow!(e))
}

#[cfg(not(feature = "converter"))]
fn install_service_view() -> Result<()> {
    Ok(())
}

/// Step 1c. The media services this process serves through the view, right after it is installed, found by name in-process: AudioFlinger and AudioPolicyService (atl-audioflinger, `media.audio_flinger` / `media.audio_policy`), the Codec2 store (atl-codec-store, `IComponentStore/default`, which AOSP's Codec2 client walks to) and the resource manager (atl-resource-manager, `media.resource_manager`, which MediaCodec waits for), the extractor service (atl-media-extractors, `media.extractor`, which MediaPlayer's setDataSource waits for; made here at launch, since its constructor loads the plugins that the in-process MediaExtractorFactory reads; skipped under `--no-media-extractor-service`, the extractor gate's break), and the media player service (atl-media-player, `media.player`, which MediaPlayer's native calls wait for; skipped under `--no-media-player-service`, the media player gate's break).
/// The PCM output opens on its first use (atl-audioflinger), so the audio server is named here only: an unreachable server does not fail the launch. `pipewire` is atld's grant (`--pipewire-socket`).
#[cfg(feature = "converter")]
fn serve_media_services(
    no_audio_service: bool,
    break_cblk: bool,
    no_media_extractor_service: bool,
    no_media_player_service: bool,
    break_mix: bool,
    pipewire: Option<&Path>,
) -> Result<()> {
    if !no_audio_service {
        atl_audioflinger::serve(
            pipewire,
            atl_audioflinger::Options {
                break_cblk,
                break_mix,
            },
        )
        .map_err(|e| anyhow!(e))?;
    }
    atl_codec_store::serve().map_err(|e| anyhow!(e))?;
    atl_resource_manager::serve().map_err(|e| anyhow!(e))?;
    if !no_media_extractor_service {
        atl_media_extractors::serve().map_err(|e| anyhow!(e))?;
    }
    if !no_media_player_service {
        atl_media_player::serve().map_err(|e| anyhow!(e))?;
    }
    Ok(())
}

#[cfg(not(feature = "converter"))]
fn serve_media_services(
    _no_audio_service: bool,
    _break_cblk: bool,
    _no_media_extractor_service: bool,
    _no_media_player_service: bool,
    _break_mix: bool,
    _pipewire: Option<&Path>,
) -> Result<()> {
    Ok(())
}

/// Step 5b''. UI mode (`ro.atl.ui=gtk`, atld `--ui gtk`): the main thread's Looper is made before Java (its MessageQueue adopts it), then GTK starts on this thread with its GLib main context mirrored
/// into the Looper (atl-platform-ui-linux `mirror`, over the `looper` seam), so GTK runs while the app's main thread idles in its Looper and a blocked one answers no ping.
/// `gralloc_node`: the run's node (`ro.atl.gpu.render_node`), whose device number every presented buffer must carry; unset: no gralloc, the window refuses every buffer.
fn start_ui(gralloc_node: Option<String>) -> Result<atl_platform_ui::PlatformUi> {
    let device = gralloc_node
        .map(|n| {
            atl_gralloc::node::device_number(std::path::Path::new(&n))
                .with_context(|| format!("gralloc node {n}"))
        })
        .transpose()?;
    let thread_looper = ffi::LooperApi::load()?.prepare_looper()?;
    atl_platform_ui::PlatformUi::attach(Box::new(looper::AndroidLooper::new(thread_looper)), device)
        .map_err(|e| anyhow!("{e}"))
}

/// AndroidRuntime::startVm's NativeBridge option from `ro.dalvik.vm.native.bridge` (unset, empty or "0": none), plus `-Xforce-nb-testing`: a non-zygote ART unloads the bridge unless forced
/// (runtime.cc `InitNonZygoteOrPostFork` action kUnload), and our app processes are not zygote forks; bridge 1 runs same-ISA bionic code through it (bridge-1 plan section 2, R4).
/// With `isa` (`--instruction-set`, every app process) also `-Xnative-bridge-isa:<isa>` (patches/aosp/art 0004), host ISA included: ART hands it to the bridge's `initialize`, which picks identity or a
/// translator, the one route the app's ISA takes. No bridge: no option (ART would refuse a foreign ISA with nothing to run it).
fn native_bridge_options(property: Option<String>, isa: Option<&str>) -> Vec<std::ffi::CString> {
    match property {
        Some(lib) if !lib.is_empty() && lib != "0" => [
            format!("-XX:NativeBridge={lib}"),
            "-Xforce-nb-testing".to_owned(),
        ]
        .into_iter()
        .chain(isa.map(|isa| format!("-Xnative-bridge-isa:{isa}")))
        .filter_map(|o| std::ffi::CString::new(o).ok())
        .collect(),
        _ => Vec::new(),
    }
}

/// Steps 0 and 1: the signal setup bionic makes, ART's functions, and the refusal to start without a property area. Every process this library runs (app, installer) starts so.
fn load_runtime() -> Result<ffi::Runtime> {
    ffi::install_signal_stack()?;
    ffi::install_crash_handler()?;
    let rt = ffi::Runtime::load()?;
    if !rt.has_property_area() {
        bail!(
            "no system property area: neither ${} nor /dev/__properties__ is a bionic property area (the broker or the harness writes one; atl-property-service)",
            atl_bionic::AREA_ENV
        );
    }
    Ok(rt)
}

fn run(argv: Vec<std::ffi::OsString>) -> Result<i32> {
    let launch = args::parse(argv).map_err(|e| anyhow!(e))?;
    let rt = load_runtime()?;
    install_service_view()?;
    serve_media_services(
        launch.no_audio_service,
        launch.break_cblk,
        launch.no_media_extractor_service,
        launch.no_media_player_service,
        launch.break_mix,
        launch.pipewire_socket.as_deref(),
    )?;
    let mut vm_options = launch.vm_options.clone();
    if launch.app {
        vm_options.extend(native_bridge_options(
            rt.property(c"ro.dalvik.vm.native.bridge"),
            launch.instruction_set.as_deref(),
        ));
    }
    let vm = rt.create_vm(&vm_options)?;
    rt.install_logger();
    if launch.app {
        // before any app code, so the guest's liblog finds the socket on its first write
        if let Err(e) = logdw::start() {
            use std::io::Write as _;
            let _ = writeln!(
                std::io::stderr(),
                "atl-app-launcher: no {}: {e:#}; liblog writes from the native-bridge guest are lost",
                logdw::PATH
            );
        }
    }
    rt.set_target_sdk(launch.target_sdk);
    let Some(class) = &launch.class else {
        bail!("Class name required");
    };
    let rc = if launch.app {
        let android = ffi::AndroidRuntime::load()?;
        android.attach(&vm)?;
        android.start_thread_pool();
        let ui = if rt.property(c"ro.atl.ui").as_deref() == Some("gtk") {
            std::ffi::CString::new(atl_gralloc::node::RENDER_NODE_PROPERTY)
                .map_err(anyhow::Error::from)
                .and_then(|name| start_ui(rt.property(&name)))
                .inspect_err(|e| {
                    use std::io::Write;
                    let _ = writeln!(std::io::stderr(), "atl-app-launcher: no UI mode: {e:#}");
                })
                .ok()
        } else {
            None
        };
        start_compositor(&vm, ui);
        vm.run_zygote_init(launch.target_sdk, class, &launch.args)
    } else {
        vm.run_main(class, &launch.args)
    };
    vm.shut_down()?;
    Ok(rc)
}

/// The launcher's whole run, from the process's arguments to its exit status (`ffi::atl_app_main`, the C entry).
fn main(argv: Vec<std::ffi::OsString>) -> i32 {
    trace::install();
    match run(argv) {
        Ok(rc) => rc,
        Err(e) => {
            use std::io::Write;
            let _ = writeln!(std::io::stderr(), "atl-app-launcher: {e:#}");
            1
        }
    }
}

#[cfg(test)]
mod nb_tests {
    use super::native_bridge_options;

    #[test]
    fn native_bridge_option_follows_the_property() {
        let o = native_bridge_options(Some("libx.so".into()), None);
        assert_eq!(
            o,
            [
                c"-XX:NativeBridge=libx.so".to_owned(),
                c"-Xforce-nb-testing".to_owned()
            ]
        );
        let o = native_bridge_options(Some("libx.so".into()), Some("arm64"));
        assert_eq!(o.last().unwrap().as_c_str(), c"-Xnative-bridge-isa:arm64");
        assert_eq!(o.len(), 3);
        assert!(native_bridge_options(Some("0".into()), Some("arm64")).is_empty());
        assert!(native_bridge_options(Some(String::new()), None).is_empty());
        assert!(native_bridge_options(None, Some("x86_64")).is_empty());
    }
}
