//! `libatl_native_bridge.so`: the NativeBridge core (plan S11 NB, bridge-1 plan section 2). ART loads it with `-XX:NativeBridge=` and asks it about every app `.so` glibc's `dlopen` refused (libnativeloader `ART_TARGET_LINUX` branch: `NativeBridgeIsSupported(path)` -> `NativeBridgeLoadLibrary(path)`).
//!
//! - `exports`: `NativeBridgeItf` and the functions behind its entries, whose shells build.rs generates from native_bridge.h (atl-bridgegen). `initialize` selects the process's engine from ART's ISA.
//! - `elf`: which libraries are ours to load: the selected engine's ELF machine and a bionic marker.
//! - `engine`: both engines, one chosen per process (`engine::Active`): identity (route N, guest bionic built for the host arch, crossings switch the thread pointer) and QEMU (a foreign ISA, the engine `.so`, `engine/qemu/mod.rs`).
//! - `loader`: the process's guest, started by the first `loadLibrary`, and the libraries loaded into it.
//!
//! Boundary crate: `unsafe` only in `exports`, `engine`, `loader` and the generated shells.
#![deny(unsafe_code)]

pub mod elf;
#[allow(unsafe_code)]
pub mod engine;
#[allow(unsafe_code)]
mod exports;
#[allow(unsafe_code)]
mod loader;

pub use exports::VERSION;

/// The file ART opens (`-XX:NativeBridge=`, from property `ro.dalvik.vm.native.bridge`, atl-property-service): cargo's cdylib name for this crate, installed unrenamed (xtask `cdylib::stage`).
pub const LIBRARY: &str = "libatl_native_bridge.so";

/// Generated by build.rs from native_bridge.h: the records (layout asserted against clang's) and the `NativeBridgeCallbacks` entry shells (the `unsafe` of the module is their calls into `exports`).
#[allow(
    clippy::all,
    unsafe_code,
    dead_code,
    reason = "generated from the C header"
)]
mod generated {
    include!(concat!(env!("OUT_DIR"), "/native_bridge.rs"));
}
