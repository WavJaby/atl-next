//! QEMU placement: the aarch64 thunk pool and binding table, the placeholder rewrites that point a guest stub, linker hook or vdso entry at a pool slot (`patch_site`, `patch_hook`, `patch_entry`), the JNI slots, and page registration with QEMU (`register`, `register_data`). Everything here is aarch64-specific; `mod.rs` holds the engine itself.

use std::sync::atomic::{AtomicUsize, Ordering};

use atl_engine_api::{PROT_EXEC, PROT_READ, PROT_WRITE};

use crate::engine::Engine as _;
use crate::engine::bindings::qemu::THUNKS;
use crate::engine::dispatch::TARGETS;
use crate::engine::image::{Image, write_sealed};
use crate::engine::jni::Class;

use super::CROSSING;

/// Generated by build.rs (`aarch64_pool.rs`): the thunk constants (`PLACEHOLDER`), and `POOL`, slot k = `svc #(BIND | k); ret`.
#[allow(
    clippy::all,
    dead_code,
    reason = "generated by atl-bridgegen (aarch64::constants_rust, aarch64::pool_rust)"
)]
pub(super) mod pool {
    include!(concat!(env!("OUT_DIR"), "/aarch64_pool.rs"));
}

/// Bytes per thunk: two instruction words.
pub(super) const THUNK_BYTES: usize = 8;
/// Next free pool slot: past the JNI ids `0..JNI_STUBS` (`jni_stub`), so `bind` never hands out a JNI id.
static NEXT: AtomicUsize = AtomicUsize::new(JNI_STUBS);

// one generated slot per binding: the pool and the table are sized by the same build-time count
const _: () = assert!(std::mem::size_of::<pool::Pool>() == THUNKS * THUNK_BYTES);

/// JNI pool ids: id `k` < `JNI_STUBS` is JNI table entry `k`, for env and vm alike (`jni_stub`). Ids from here up are bound host functions.
pub const JNI_STUBS: usize = crate::engine::bindings::JNI_STUBS;

/// A guest-callable address that crosses to host function `target` with an integer result ([`bind_result`]). None when the pool is used up.
pub fn bind(target: usize) -> Option<usize> {
    bind_result(target, Class::Int)
}

/// A guest-callable address that crosses to host function `target`, whose result is of class `ret`: the address of a free pool slot, which the binding trap routes to `target` and answers by `ret` (dispatch.rs `call_binding`). None when the pool is used up.
pub fn bind_result(target: usize, ret: Class) -> Option<usize> {
    let slot = NEXT.fetch_add(1, Ordering::Relaxed);
    if slot >= THUNKS {
        return None;
    }
    TARGETS[slot]
        .set((target, ret))
        .expect("a pool slot is bound once: NEXT only grows");
    Some((&raw const pool::POOL) as usize + slot * THUNK_BYTES)
}

/// The guest-callable address of JNI table slot `slot`: pool slot `slot` itself. Its trap is routed by id to the host object's own table (`dispatch::call_jni`), not through `TARGETS`.
pub fn jni_stub(slot: usize) -> usize {
    assert!(slot < JNI_STUBS, "JNI slot {slot} past the stub array");
    (&raw const pool::POOL) as usize + slot * THUNK_BYTES
}

/// The two instruction words at `addr`.
fn read_words(addr: usize) -> [u32; 2] {
    // SAFETY: `addr` is an instruction site of a guest image the engine mapped, or a stub the guest passed to `native_bridge_intercept_symbol`; its 8 bytes are readable.
    unsafe { (addr as *const [u32; 2]).read_unaligned() }
}

/// The 8-byte placeholder of an unbound stub: `ldr x3, =0; blr x3`, assembled to `mov x3, #0; blr x3`.
#[cfg(not(atl_nb_qe_prefix))]
pub fn is_stub(addr: usize) -> bool {
    read_words(addr) == pool::PLACEHOLDER
}

/// Deliberate break of the placeholder shape check (`ATL_NB_BREAK=qe_prefix`): only the first two bytes decide, so a site whose tail differs is taken for a stub.
#[cfg(atl_nb_qe_prefix)]
pub fn is_stub(addr: usize) -> bool {
    read_words(addr)[0] & 0xffff == pool::PLACEHOLDER[0] & 0xffff
}

/// The words of the pool slot at address `thunk` (from `bind`); None when `thunk` is no slot.
fn slot_words(thunk: usize) -> Option<[u32; 2]> {
    let base = &raw const pool::POOL as usize;
    let slot = thunk.checked_sub(base)? / THUNK_BYTES;
    pool::POOL.0.get(slot).copied()
}

/// Two instruction words as AArch64 stores them: little-endian, first word first.
fn word_bytes(words: [u32; 2]) -> [u8; THUNK_BYTES] {
    let mut out = [0u8; THUNK_BYTES];
    out[..4].copy_from_slice(&words[0].to_le_bytes());
    out[4..].copy_from_slice(&words[1].to_le_bytes());
    out
}

/// Replaces the stub at `addr` (`is_stub`) with the thunk `thunk` (from `bind`), in sealed guest text. False when `addr` is no stub or `thunk` is no pool slot.
pub fn patch_site(addr: usize, thunk: usize) -> bool {
    if !is_stub(addr) {
        return false;
    }
    let Some(words) = slot_words(thunk) else {
        return false;
    };
    write_sealed(addr, &word_bytes(words));
    true
}

/// Writes the thunk `words` over the placeholder at `at`, in an image still writable (before `seal`).
fn write_before_seal(at: usize, words: [u32; 2]) {
    // SAFETY: `at` is an 8-byte placeholder the caller found with `is_stub` in a segment it mapped and has not sealed.
    unsafe {
        std::ptr::copy_nonoverlapping(word_bytes(words).as_ptr(), at as *mut u8, THUNK_BYTES)
    };
}

/// Routes the linker hook at `at` (its placeholder, before `seal`) to a thunk of `host`.
pub fn patch_hook(at: usize, host: usize) -> Result<(), &'static str> {
    if !is_stub(at) {
        return Err("not the 8-byte placeholder this engine rewrites");
    }
    let thunk = bind(host).ok_or("out of thunks")?;
    let words = slot_words(thunk).ok_or("bound thunk is no pool slot")?;
    write_before_seal(at, words);
    Ok(())
}

/// Bytes of a vdso entry's body that may hold its placeholder: `nop; nop; ldr x3, =0; blr x3` (NBS vdso_arm64.S:50-54), the longest.
/// Break `qe_site` shortens it to the symbol's own 8 bytes, so `native_bridge_call_guest` (placeholder at +8) is not found.
#[cfg(not(atl_nb_qe_site))]
const ENTRY_BODY_BYTES: usize = 16;
#[cfg(atl_nb_qe_site)]
const ENTRY_BODY_BYTES: usize = THUNK_BYTES;
/// Placeholders sit on instruction-word boundaries.
const WORD_BYTES: usize = 4;

/// The `st_value` of a .dynsym entry (`Image::dynsym_values`'s address): the symbol's address before the load bias.
fn st_value(value_at: usize) -> usize {
    // SAFETY: `value_at` is the st_value field of a .dynsym entry of an image this engine mapped and has not sealed (`Image::dynsym_values`), 8 readable bytes.
    unsafe { (value_at as *const usize).read_unaligned() }
}

/// The one placeholder whose 8 bytes lie in `[start, end)`, on a word boundary. Absent or more than one is an error: a vdso that differs from the pin fails closed.
fn find_placeholder(start: usize, end: usize) -> Result<usize, &'static str> {
    let mut found = None;
    let mut at = start;
    while at + THUNK_BYTES <= end {
        if is_stub(at) && found.replace(at).is_some() {
            return Err("two placeholders in the entry's body");
        }
        at += WORD_BYTES;
    }
    found.ok_or("no placeholder in the entry's body")
}

/// Routes the vdso entry whose st_value field is at `value_at` to a host function (before `seal`). Its placeholder is searched in the entry's body: from the symbol up to the next dynamic symbol, at most [`ENTRY_BODY_BYTES`]. Symbols carry no size here (asm symbols, size 0), so the next symbol is the bound.
pub fn patch_entry(vdso: &Image, value_at: usize, host: usize) -> Result<(), &'static str> {
    let start = vdso.bias + st_value(value_at);
    let next = vdso
        .dynsym_values()
        .iter()
        .map(|&(_, at)| vdso.bias + st_value(at))
        .filter(|&addr| addr > start)
        .min()
        .unwrap_or(usize::MAX);
    let at = find_placeholder(start, next.min(start + ENTRY_BODY_BYTES))?;
    let thunk = bind(host).ok_or("out of thunks")?;
    let words = slot_words(thunk).ok_or("bound thunk is no pool slot")?;
    write_before_seal(at, words);
    Ok(())
}

/// Maps a host data range as readable guest memory, for a call that passes its address (a page-aligned static of the gate; the engine maps whole pages).
pub fn register_data(start: usize, len: usize) -> Result<(), String> {
    CROSSING.map(start, len, PROT_READ)
}

/// Registers the host pool (executable) and every segment of `images` with QEMU, identity mapped, so a guest fetch from them does not fault. Call before the first guest fetch from them.
/// Break `qe_nomap` skips it: a guest fetch from a placed site then faults.
#[cfg(not(atl_nb_qe_nomap))]
pub fn register(images: &[&Image]) -> Result<(), String> {
    let pool_start = (&raw const pool::POOL) as usize;
    CROSSING.map(
        pool_start,
        std::mem::size_of::<pool::Pool>(),
        PROT_READ | PROT_EXEC,
    )?;
    for image in images {
        for &(start, len, prot) in image.segments() {
            CROSSING.map(
                start,
                len,
                (prot as u32) & (PROT_READ | PROT_WRITE | PROT_EXEC),
            )?;
        }
    }
    Ok(())
}

/// Break `qe_nomap` (see [`register`]): no page is registered.
#[cfg(atl_nb_qe_nomap)]
pub fn register(_images: &[&Image]) -> Result<(), String> {
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The placeholder is the stub; a site with the same first two bytes but another tail (`br x3`) is not. Break `qe_prefix` takes it for one.
    #[test]
    fn stub_shape_is_the_whole_placeholder() {
        let placeholder: [u32; 2] = pool::PLACEHOLDER;
        // br x3 = d61f0060 (ARM ARM): the placeholder's `mov x3, #0` word, another second word
        let br: [u32; 2] = [placeholder[0], 0xD61F_0060];
        assert!(is_stub(placeholder.as_ptr() as usize));
        assert!(!is_stub(br.as_ptr() as usize));
    }

    /// An entry body holds exactly one placeholder: the search finds it at its word offset, and fails closed on none or two. The words are ARM ARM literals: `nop` d503201f, `mov x3, #0` d2800003, `blr x3` d63f0060.
    #[test]
    fn entry_body_holds_one_placeholder() {
        const NOP: u32 = 0xD503_201F;
        const MOV_X3_0: u32 = 0xD280_0003;
        const BLR_X3: u32 = 0xD63F_0060;
        // nop, nop, placeholder: the placeholder at byte 8 (vdso_arm64.S native_bridge_call_guest)
        let body: [u32; 4] = [NOP, NOP, MOV_X3_0, BLR_X3];
        let base = body.as_ptr() as usize;
        assert_eq!(find_placeholder(base, base + 16), Ok(base + 8));
        // the range ends before the placeholder: none
        assert!(find_placeholder(base, base + 8).is_err());
        // two placeholders in one range: ambiguous
        let two: [u32; 4] = [MOV_X3_0, BLR_X3, MOV_X3_0, BLR_X3];
        let base2 = two.as_ptr() as usize;
        assert!(find_placeholder(base2, base2 + 16).is_err());
    }
}
