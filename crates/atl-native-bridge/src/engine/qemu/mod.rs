//! The QEMU engine (QEMU bridge plan Q4; selected per process, `engine/mod.rs` `Active::Qemu`): the guest is aarch64 under QEMU's user-mode TCG, so a crossing is an `svc` trap, not a thread-pointer switch. The second engine beside `identity/mod.rs`; the names and contracts match.
//! Placement (pool, stub and entry patching, JNI slots, page registration) is in `place.rs`; this file holds the engine's table, its start and its CPUs. The trap body is in `dispatch.rs`.
//! A binding thunk is two words, `svc #(BIND | id)` then `ret`. The pool (`place.rs`, generated by build.rs through atl-bridgegen) holds slot k = thunk k, page aligned in `.rodata`. `bind` hands out slots; `patch_site` and `patch_hook` copy a slot's words over a placeholder (`mov x3,#0; blr x3`) of the guest image; [`on_trap`] calls the host target of a binding trap.
//! Start ([`run`]): [`boot`] dlopens the engine `.so` and creates its one engine on a static boot executable (C ABI `atl_engine`, QEMU bridge plan Q5-1b; the rlib spike route is retired). The BOOT trap answers at once, so `create` returns with the engine up. [`attach_current`] then gives this thread a guest CPU, and `Guest::start` runs on it as on x86 -- map, place, register the pages with QEMU ([`register`]), `__linker_init` through [`call_guest`] -- and the caller's continuation gets the started guest; its answer is the process's exit status.
//! The thread pointer is TPIDR_EL0 in the guest CPU state: a guest call runs on the record's `guest_fs` and stores back what the guest left there, as the x86 crossing does with FS. The host thread pointer is never touched.
//! The JNI stubs are pool ids below `JNI_STUBS`, routed to the host object's own table (`dispatch::call_jni`, integer lanes, Q6-2). A thread gets its guest CPU on its first guest call (`attach_current`, `detach_current`; `Engine::attach`).

