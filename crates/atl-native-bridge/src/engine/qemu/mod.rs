/// The guest ISA (atl-android-paths `native_bridge_bin` / `native_bridge_lib` directory): QEMU runs aarch64 guests.
pub const GUEST_ISA: &str = "arm64";
/// The ELF machine of [`GUEST_ISA`] libraries (elf.rs `classify` under this engine).
pub const GUEST_MACHINE: object::elf::Machine = object::elf::EM_AARCH64;

// the ABI's PROT_* are libc's values, so a segment's prot passes through unchanged
const _: () = assert!(libc::PROT_READ == PROT_READ as i32);
const _: () = assert!(libc::PROT_WRITE == PROT_WRITE as i32);
const _: () = assert!(libc::PROT_EXEC == PROT_EXEC as i32);

/// The engine's table and handle ([`boot`]): one engine per process.
struct Engine {
    table: AtlEngine,
    handle: *mut AtlEngineHandle,
}
// SAFETY: the table is function pointers and the handle is the engine's own; the ABI allows create, map and attach from any thread, and call and detach on the thread that attached.
unsafe impl Send for Engine {}
// SAFETY: as for Send.
unsafe impl Sync for Engine {}
static ENGINE: OnceLock<Engine> = OnceLock::new();
/// The trap callback [`boot`] installed; [`host_trap`] reaches it.
static ON_TRAP: OnceLock<OnTrap> = OnceLock::new();
/// The auxv QEMU built for the boot executable (BOOT's x0): this guest's kernel auxv ([`kernel_auxv`]).
static BOOT_AUXV: AtomicUsize = AtomicUsize::new(0);

thread_local! {
    /// This thread's attached guest CPU ([`attach_current`]): the state guest calls run on. Null before attach.
    static CPU: Cell<*mut AtlCpu> = const { Cell::new(std::ptr::null_mut()) };
    /// The guest stack `attach_ex` gave this thread's CPU (base, len, guard filled); zero before attach.
    static STACK: Cell<AtlStack> = const { Cell::new(AtlStack { size: 0, guard: 0, base: 0, len: 0 }) };
    /// Guest calls running on this thread ([`call_on`], nested through traps).
    static DEPTH: Cell<u32> = const { Cell::new(0) };
}

/// Guest calls running on this thread: 1 inside a trap means the trapping code runs in the thread's outermost guest call.
pub(super) fn call_depth() -> u32 {
    DEPTH.with(Cell::get)
}

/// From inside a trap callback: the trap's return ends the guest call it interrupted, its answer becoming that call's (`atl_engine.end_call`).
pub(super) fn end_call() -> Result<(), String> {
    let e = engine();
    let end = e
        .table
        .end_call
        .unwrap_or_else(|| unsupported("engine table has no end_call"));
    // SAFETY: the handle is the one create returned.
    match unsafe { end(e.handle) } {
        0 => Ok(()),
        rc => Err(format!("end_call: {}", errno_text(rc))),
    }
}

/// Boots the engine `library` (the engine `.so`) on the static aarch64 `boot_exe`, which must raise BOOT with its auxv in x0. `on_trap` gets every trap of the engine on the trapping thread, BOOT included. Returns once BOOT ran and the engine is up; the guest runs after [`attach_current`]. Once per process.
pub fn boot(library: &Path, boot_exe: &Path, on_trap: OnTrap) -> Result<(), String> {
    // the process's engine becomes QEMU before anything binds: tables, thread layout and placement follow `active()`
    super::claim(Some(GUEST_ISA))?;
    let lib = os_cstring(library)?;
    let exe = os_cstring(boot_exe)?;
    ON_TRAP
        .set(on_trap)
        .map_err(|_| "qemu crossing: boot called twice".to_owned())?;
    // SAFETY: lib is NUL-terminated; the library's initialisers are QEMU's own (QOM type registration) and run here; the handle is never closed.
    let handle = unsafe { libc::dlopen(lib.as_ptr(), libc::RTLD_NOW | libc::RTLD_LOCAL) };
    if handle.is_null() {
        return Err(format!("dlopen {}: {}", library.display(), dlerror()));
    }
    // SAFETY: handle is the library's, and the name is NUL-terminated.
    let table = unsafe { libc::dlsym(handle, c"atl_engine".as_ptr()) }.cast::<AtlEngine>();
    if table.is_null() {
        return Err(format!(
            "{}: no atl_engine: {}",
            library.display(),
            dlerror()
        ));
    }
    // SAFETY: the symbol is the engine's table, a static of the never-closed library.
    let table = unsafe { *table };
    check_engine_table(&table).map_err(|e| format!("{}: {e}", library.display()))?;
    let create = table
        .create
        .unwrap_or_else(|| unsupported("engine table has no create"));
    let host = AtlHost {
        major: ABI_MAJOR,
        minor: ABI_MINOR,
        size: std::mem::size_of::<AtlHost>() as u32,
        ctx: std::ptr::null_mut(),
        trap: Some(host_trap),
        trap_ex: Some(host_trap_ex),
    };
    let mut engine = std::ptr::null_mut();
    // SAFETY: host and exe live for the call (the ABI); engine is an out parameter. create returns after BOOT answered.
    let rc = unsafe { create(&host, exe.as_ptr(), &mut engine) };
    if rc != 0 {
        return Err(format!("engine create: {}", errno_text(rc)));
    }
    ENGINE
        .set(Engine {
            table,
            handle: engine,
        })
        .map_err(|_| "qemu crossing: engine set twice".to_owned())
}

/// NativeBridge `getSignalHandler` under this engine: [`fault`] for SIGSEGV and SIGBUS, whose guest faults the engine owns; none for any other signal.
pub fn signal_handler(sig: i32) -> Option<super::SignalHandler> {
    (sig == libc::SIGSEGV || sig == libc::SIGBUS).then_some(fault as super::SignalHandler)
}

/// The special handler ART registers from [`signal_handler`] (full mask, `SIGCHAIN_ALLOW_NORETURN`): the engine's `fault` entry, which may not return. ART asks at `initialize`, which boots the engine first; a signal before [`boot`] published the engine is declined.
///
/// # Safety
/// Sigchain calls it with the kernel's siginfo and ucontext of one delivery.
unsafe extern "C" fn fault(
    sig: i32,
    info: *mut crate::generated::siginfo_t,
    uc: *mut c_void,
) -> bool {
    let Some(f) = ENGINE.get().and_then(|e| e.table.fault) else {
        return false;
    };
    // SAFETY: the delivery's siginfo and ucontext, passed through as the ABI's fault takes them.
    unsafe { f(sig, info.cast(), uc) }
}

/// The engine's host trap for BOOT and REPORT (`atl_host.trap`): decodes the kind, records BOOT's auxv, and calls the callback [`boot`] installed. Answers x0.
///
/// # Safety
/// The engine calls it with `regs` pointing at eight readable u64 (the ABI).
unsafe extern "C" fn host_trap(_ctx: *mut c_void, kind: u32, _id: u32, regs: *const u64) -> u64 {
    // SAFETY: eight u64 at regs, per the ABI; an unaligned read is fine for any alignment.
    let r = unsafe { regs.cast::<[u64; 8]>().read_unaligned() };
    const BOOT: u32 = TrapKind::Boot as u32;
    const REPORT: u32 = TrapKind::Report as u32;
    let trap = match kind {
        BOOT => Trap::Boot(r[0]),
        REPORT => Trap::Report(r[0]),
        other => unsupported(&format!(
            "qemu crossing: engine trap kind {other} on the BOOT/REPORT entry"
        )),
    };
    if let Trap::Boot(auxv) = trap {
        BOOT_AUXV.store(auxv as usize, Ordering::Release);
    }
    dispatch_trap(trap).x0
}

/// The engine's host trap for CALL and BIND (`atl_host.trap_ex`): the lanes in, the callback's answer out as `x[0]` and `v[0]`.
///
/// # Safety
/// The engine calls it with `lanes` pointing at one live `AtlLanes` (the ABI), read and answered before it returns.
unsafe extern "C" fn host_trap_ex(_ctx: *mut c_void, kind: u32, id: u32, lanes: *mut AtlLanes) {
    const CALL: u32 = TrapKind::Call as u32;
    const BIND: u32 = TrapKind::Bind as u32;
    // SAFETY: one AtlLanes at lanes, per the ABI.
    let l = unsafe { lanes.read() };
    // break `qa_v_lane` (qemu-abi gate, `v`): FP lane i arrives as lane i+1
    #[cfg(atl_qa_v_lane)]
    let l = AtlLanes {
        v: std::array::from_fn(|i| l.v[(i + 1) % 8]),
        ..l
    };
    // break `qa_stack_off` (qemu-abi gate, `k`): stack word i arrives as word i+1
    #[cfg(atl_qa_stack_off)]
    let l = AtlLanes {
        stack: std::array::from_fn(|i| l.stack[(i + 1) % 8]),
        ..l
    };
    let trap = match kind {
        CALL => Trap::Call(l),
        BIND => Trap::Bind { id, lanes: l },
        other => unsupported(&format!(
            "qemu crossing: engine trap kind {other} on the CALL/BIND entry"
        )),
    };
    let answer = dispatch_trap(trap);
    // SAFETY: lanes is the engine's and still live (the ABI); the engine sets the guest's v0 and x0 from these two answers.
    let out = unsafe { &mut *lanes };
    out.x[0] = answer.x0;
    out.v[0] = answer.v0;
}

/// The callback [`boot`] installed, on one trap.
fn dispatch_trap(trap: Trap) -> Answer {
    let on_trap = ON_TRAP
        .get()
        .unwrap_or_else(|| unsupported("qemu crossing: a trap before boot installed its callback"));
    on_trap(trap)
}

/// The process's engine, from [`boot`].
fn engine() -> &'static Engine {
    ENGINE
        .get()
        .unwrap_or_else(|| unsupported("qemu crossing: no engine (boot has not run)"))
}

/// Gives the calling thread a guest CPU (`atl_engine.attach_ex`: a copy of the boot CPU) and makes it this thread's CPU for [`call_guest`], [`call`] and [`register`]. Once per thread, after [`boot`]: a second call keeps the first CPU. [`detach_current`] takes it back at thread exit.
pub fn attach_current() -> Result<(), String> {
    attach_current_ex(AtlStack::default()).map(|_| ())
}

/// [`attach_current`] on a guest stack sized by `stack.size` and `stack.guard` (0 = the engine's default; `atl_engine.attach_ex`). Returns the stack with `base` and `len` filled; `None` when this thread already had its CPU (its stack unchanged).
pub fn attach_current_ex(mut stack: AtlStack) -> Result<Option<AtlStack>, String> {
    if !CPU.with(Cell::get).is_null() {
        return Ok(None);
    }
    let e = engine();
    let attach_ex = e
        .table
        .attach_ex
        .unwrap_or_else(|| unsupported("engine table has no attach_ex"));
    let mut cpu = std::ptr::null_mut();
    // SAFETY: the handle is the one create returned; stack is a live atl_stack, cpu an out parameter.
    let rc = unsafe { attach_ex(e.handle, &mut stack, &mut cpu) };
    if rc != 0 {
        return Err(format!("attach: {}", errno_text(rc)));
    }
    CPU.with(|c| c.set(cpu));
    STACK.with(|s| s.set(stack));
    Ok(Some(stack))
}

/// Takes the calling thread's CPU back (`atl_engine.detach`) after its last guest call; a thread without one does nothing. Detached on the thread that attached it (the ABI).
pub fn detach_current() {
    let cpu = CPU.with(|c| c.replace(std::ptr::null_mut()));
    if cpu.is_null() {
        return;
    }
    STACK.with(|s| s.set(AtlStack::default()));
    let e = engine();
    let detach = e
        .table
        .detach
        .unwrap_or_else(|| unsupported("engine table has no detach"));
    // SAFETY: the handle is the one create returned; cpu came from attach on this thread and is detached once (its slot is cleared above).
    unsafe { detach(e.handle, cpu) };
}

/// Calls guest `f` on this thread's CPU with thread pointer `tp` in and out (`atl_engine.call_ex`): `lanes` in, the answer in `lanes.x[0]` and `lanes.v[0]`. Nests: from inside a trap callback too.
fn call_on(tp: &mut u64, f: u64, lanes: &mut AtlLanes) {
    let e = engine();
    let cpu = CPU.with(Cell::get);
    if cpu.is_null() {
        unsupported("qemu crossing: no guest CPU on this thread (attach_current)");
    }
    let ex = e
        .table
        .call_ex
        .unwrap_or_else(|| unsupported("engine table has no call_ex"));
    DEPTH.with(|d| d.set(d.get() + 1));
    // SAFETY: handle and cpu are the engine's; cpu was attached on this thread (CPU is set only by attach_current); tp and lanes are writable and live for the call.
    unsafe { ex(e.handle, cpu, tp, f, lanes) };
    DEPTH.with(|d| d.set(d.get() - 1));
}

/// Runs guest `f` for a host->guest down call (Q6-4, dispatch.rs `down_body`): on the calling thread's record (`thread::attach_current`, which attaches the CPU and the guest TCB on demand), with the record's thread pointer in and out, and `lanes` in and out (`call_ex`).
pub(super) fn call_down(f: usize, lanes: &mut AtlLanes) {
    // SAFETY: the record is this thread's and lives until its exit (thread.rs `attach_current`, `detach`); no other borrow of it is live here.
    let ht = unsafe { &mut *super::thread::attach_current() };
    let mut tp = ht.guest_fs() as u64;
    call_on(&mut tp, f as u64, lanes);
    ht.set_guest_fs(tp as usize);
}

/// Calls guest `f(args)` (integer arguments, at most eight) on this thread's CPU with thread pointer 0 (the boot executable has none); returns x0. For the gates; the crossing uses [`call_guest`].
pub fn call(f: u64, args: &[u64]) -> u64 {
    assert!(args.len() <= 8, "{} arguments, x0..x7 only", args.len());
    let mut lanes = AtlLanes::default();
    lanes.x[..args.len()].copy_from_slice(args);
    call_ex(f, &mut lanes);
    lanes.x[0]
}

/// Calls guest `f` with `lanes` on this thread's CPU with thread pointer 0; the answer is `lanes.x[0]` and `lanes.v[0]`. For the gates (qemu-abi's host-to-guest checks).
pub fn call_ex(f: u64, lanes: &mut AtlLanes) {
    let mut tp = 0;
    call_on(&mut tp, f, lanes);
}

/// Starts the guest: [`boot`] on `library` and `boot_exe`, [`attach_current`], `Guest::start(&cfg)`, then `then` with its result. `then`'s answer is the process's exit status, so this returns only if the start fails.
pub fn run(
    library: &Path,
    boot_exe: &Path,
    cfg: Config,
    then: fn(Result<super::Guest, String>) -> u64,
) -> Result<std::convert::Infallible, String> {
    boot(library, boot_exe, on_boot)?;
    attach_current()?;
    let answer = then(super::Guest::start(&cfg));
    std::process::exit(i32::try_from(answer).unwrap_or(i32::MAX))
}

/// The trap callback of [`run`]: BOOT is the start, which `run` does itself, so it answers 0; the rest is [`on_trap`].
fn on_boot(trap: Trap) -> Answer {
    match trap {
        Trap::Boot(_) => Answer::default(),
        other => on_trap(other),
    }
}

/// The dynamic loader's last error, or a placeholder when there is none.
fn dlerror() -> String {
    // SAFETY: dlerror returns the calling thread's last error message, or null.
    let msg = unsafe { libc::dlerror() };
    if msg.is_null() {
        return "no dlerror message".to_owned();
    }
    // SAFETY: non-null and NUL-terminated, owned by libc until the next dl call.
    unsafe { CStr::from_ptr(msg) }
        .to_string_lossy()
        .into_owned()
}

/// The engine's failure (a negative errno, ABI) as text.
fn errno_text(rc: c_int) -> String {
    std::io::Error::from_raw_os_error(-rc).to_string()
}

/// A host path as the NUL-terminated bytes the C ABI and dlopen take.
fn os_cstring(p: &Path) -> Result<CString, String> {
    CString::new(p.as_os_str().as_encoded_bytes()).map_err(|e| format!("{}: {e}", p.display()))
}

/// The kernel's auxv for this guest: QEMU's for the boot executable, so hwcaps, page size and AT_RANDOM describe the emulated CPU and its process (an x86 host's AT_HWCAP bits mean nothing to arm64 bionic's ifunc resolvers). `args::build` replaces the image entries.
pub fn kernel_auxv() -> Result<Vec<(usize, usize)>, String> {
    let mut at = BOOT_AUXV.load(Ordering::Acquire);
    if at == 0 {
        return Err("qemu crossing: no BOOT auxv".into());
    }
    let mut out = Vec::new();
    loop {
        // SAFETY: `at` walks the auxv QEMU wrote on the boot executable's stack (guest = host address, `boot` checks identity), AT_NULL-terminated pairs of words; that stack lives as long as the boot thread.
        let (k, v) = unsafe {
            (
                (at as *const usize).read(),
                (at as *const usize).add(1).read(),
            )
        };
        if k == libc::AT_NULL as usize {
            return Ok(out);
        }
        out.push((k, v));
        at += 2 * std::mem::size_of::<usize>();
    }
}

/// Makes `images` reachable by guest fetches: registers the pool and every segment with QEMU ([`register`]). Runs on an attached thread, before the first guest call. Host data needs no registration for a syscall: under identity, QEMU's syscall check accepts a range no QEMU page covers.
pub fn map_guest(images: &[&Image]) -> Result<(), String> {
    register(images)
}

/// Whether the crossing is available: QEMU's user-mode core needs no thread-pointer feature.
pub fn supported() -> bool {
    true
}

/// bionic's TCB slots on arm64, `MIN_TLS_SLOT..=MAX_TLS_SLOT` around the thread pointer (tls_defines.h).
const TCB_WORDS: usize = (MAX_TLS_SLOT - MIN_TLS_SLOT + 1) as usize;

/// A scratch TCB's thread pointer for `Tp::Bootstrap`: `__linker_init` runs on a zeroed TCB, so a TLS or stack-guard read before the linker's own `__set_tls` (NBS `__libc_init_main_thread_early`) sees zeros, not address 0. Leaked: a few words per call. The x86 crossing's bootstrap record (host FS during the call) has no counterpart: the host thread pointer is never the guest's here.
fn bootstrap_tcb() -> usize {
    let tcb: &'static mut [usize; TCB_WORDS] = Box::leak(Box::new([0; TCB_WORDS]));
    // TP = &slot 0: -MIN_TLS_SLOT words into the TCB
    tcb.as_ptr() as usize + MIN_TLS_SLOT.unsigned_abs() as usize * std::mem::size_of::<usize>()
}

/// The arch's own words of guest TCB `tp`: none. arm64 bionic's TCB has no self pointer (TP = &slot 0, tls_defines.h), and this crossing finds its state without the TCB (a trap runs on the host thread pointer), so `TLS_SLOT_NATIVE_BRIDGE_GUEST_STATE` stays zero.
///
/// # Safety
/// As the x86 seam's: `tp` is a guest TCB, live while `ht` is used on it.
pub unsafe fn init_tcb(_tp: usize, _ht: *mut HostThread) {}

/// The QEMU crossing, the QEMU engine's `Engine`. Its CPU is the calling thread's own (`attach_current`); the shared crossing record (`HostThread`) holds the guest thread pointer -- the QEMU thread pointer lives in the engine's CPU state, so the record's host-FS and shadow-stack words go unused here.
pub struct Qemu;

/// The QEMU engine (`engine/mod.rs` `Active::Qemu`).
pub const CROSSING: Qemu = Qemu;

impl super::Engine for Qemu {
    type Cpu = HostThread;

    /// Boots the installed engine `.so` on its boot executable (atl-android-paths `engine_library` / `engine_boot`), then gives the calling thread its guest CPU. Other threads attach on their first guest call (`Engine::attach`).
    fn start(&self) -> Result<(), String> {
        boot(
            Path::new(&atl_android_paths::engine_library(GUEST_ISA)),
            Path::new(&atl_android_paths::engine_boot(GUEST_ISA)),
            on_boot,
        )?;
        attach_current()
    }

    /// The engine's `map`: marks `[start, start + len)` as guest memory with `prot` (`PROT_*`; identity addresses). Refused before the engine is up.
    fn map(&self, start: usize, len: usize, prot: u32) -> Result<(), String> {
        let e = engine();
        let f = e
            .table
            .map
            .unwrap_or_else(|| unsupported("engine table has no map"));
        // SAFETY: the engine handle is live; the range is host memory the caller owns (identity, the ABI's contract).
        let rc = unsafe { f(e.handle, start as u64, len as u64, prot) };
        if rc == 0 {
            Ok(())
        } else {
            Err(format!("map {start:#x}+{len:#x}: {}", errno_text(rc)))
        }
    }

    /// The calling thread's CPU ([`attach_current_ex`] with `req`): once per thread, so the thread's first guest call has one. Answers the CPU's guest stack, the first attach's on a repeat.
    fn attach(&self, req: super::StackReq) -> Result<super::Stack, String> {
        attach_current_ex(AtlStack {
            size: req.size as u64,
            guard: req.guard as u64,
            ..AtlStack::default()
        })?;
        let s = STACK.with(Cell::get);
        Ok(super::Stack {
            base: s.base as usize,
            len: s.len as usize,
            guard: s.guard as usize,
        })
    }

    /// Takes the calling thread's CPU back ([`detach_current`]) at thread exit, after its guest destructors.
    fn detach(&self) {
        detach_current();
    }

    /// Calls guest `f(a, b, c, d)` on this thread's guest CPU with TPIDR_EL0 = the record's guest thread pointer, and stores back the one the guest returned with (the linker installs its own during `__linker_init`).
    ///
    /// # Safety
    /// As the x86 seam's: `f` is guest code with up to four integer arguments, `cpu` this thread's record.
    unsafe fn call(
        &self,
        cpu: &mut HostThread,
        tp: super::Tp,
        f: usize,
        args: &[usize; 4],
    ) -> usize {
        cpu.set_guest_fs(match tp {
            super::Tp::Bootstrap => bootstrap_tcb(),
            super::Tp::Guest(t) => t,
        });
        let mut lanes = AtlLanes::default();
        lanes.x[..4].copy_from_slice(&args.map(|v| v as u64));
        let mut guest_tp = cpu.guest_fs() as u64;
        call_on(&mut guest_tp, f as u64, &mut lanes);
        cpu.set_guest_fs(guest_tp as usize);
        lanes.x[0] as usize
    }
}

