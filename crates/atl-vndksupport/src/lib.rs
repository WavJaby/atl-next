//! libvndksupport for AOSP code built against glibc: loading a same-process HAL (SP-HAL) library, e.g.
//! libui's Gralloc5 loading the AIDL mapper. AOSP (`libvndksupport/linker.cpp`) opens it in the linker
//! namespace `sphal`, else `vendor`, else `default`, and with none of them exported falls back to
//! `dlopen(name, flag)` in the caller's namespace. This host has one namespace, so the fallback is the
//! whole behaviour: `dlopen` / `dlclose` with the caller's flags, returning their results (AOSP's
//! fallback warning is left out: here it is the normal path, not a misconfiguration).
//!
//! A separate crate, not part of atl-bionic: it is libvndksupport's API (system/core), not bionic's, and
//! is its own module with its own shared object, as in AOSP. When linker namespaces exist
//! (libnativeloader), this is where `sphal` is looked up. Boundary crate: `unsafe` only in `ffi`.
#![deny(unsafe_code)]

/// Generated by build.rs from AOSP's pinned header.
mod generated {
    pub mod linker {
        include!(concat!(env!("OUT_DIR"), "/linker.rs"));
    }
}

#[allow(unsafe_code)]
mod ffi;
