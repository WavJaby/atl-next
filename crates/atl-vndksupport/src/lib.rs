//! libvndksupport for AOSP code built against glibc: loading a same-process HAL (SP-HAL) library, e.g.
//! libui's Gralloc5 loading the AIDL mapper. As AOSP's (`libvndksupport/linker.cpp`): look up the
//! exported linker namespace `sphal` and `android_dlopen_ext` the library in it; unloading is `dlclose`.
//! Both calls go to libc's provider, atl-bionic, whose `linker` is the one place namespaced loads go: one
//! namespace there now, our libnativeloader's namespaces later, with nothing to change here. AOSP's
//! no-namespace fallback and its failure log are left out: atl-bionic exports every namespace name, and
//! a failure stays in `dlerror` for the caller.
//!
//! A separate crate, not part of atl-bionic: it is libvndksupport's API (system/core), not bionic's, and
//! is its own module with its own shared object, as in AOSP; it reaches bionic's API only through its
//! C ABI, as AOSP's does. Boundary crate: `unsafe` only in `ffi`.
#![deny(unsafe_code)]

/// Generated by build.rs from AOSP's pinned sources: the exports' header, and the bionic API imported.
mod generated {
    pub mod linker {
        include!(concat!(env!("OUT_DIR"), "/linker.rs"));
    }
    pub mod dlext {
        include!(concat!(env!("OUT_DIR"), "/dlext.rs"));
    }
    pub mod libdl_android {
        include!(concat!(env!("OUT_DIR"), "/libdl_android.rs"));
    }
}

#[allow(unsafe_code)]
mod ffi;
