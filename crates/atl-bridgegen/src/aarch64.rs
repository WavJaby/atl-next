//! aarch64 guest thunks for the QEMU engine (QEMU bridge plan Q4). A binding thunk is two words, `svc #(BIND | id)` then `ret`; the svc immediate carries the binding id, which atl-qemu-engine's trap decode reads.
//! One encoder ([`place_words`]), three emitted forms: [`pool_asm`] for a guest fixture (assembled by the NDK clang, no host code links it), [`pool_rust`] for a host pool, and [`constants_rust`] for the host constants. The host forms are `include!`d from the consumer's build.rs output, so no crate depends on this one at run time.
//! The pool is a page-aligned run of thunks in an executable section (guest) or a page-aligned `static` (host), slot k holding binding k.

use std::fmt::Write;

/// `svc #0`: the base encoding, imm16 at bits 20:5.
pub const SVC: u32 = 0xD400_0001;
/// `ret` (through x30).
pub const RET: u32 = 0xD65F_03C0;
/// Bit 15 of the svc immediate: a binding. The low 15 bits are the id, so 32768 bindings.
pub const BIND: u32 = 0x8000;
/// The placeholder body of an intercept stub as the NB sources ship it: `ldr x3, =0; blr x3`, assembled to `mov x3, #0; blr x3`. In-place writes replace it.
pub const PLACEHOLDER: [u32; 2] = [0xD280_0003, 0xD63F_0060];

/// The two words of binding `id`'s thunk. Panics when `id` does not fit the immediate (`id >= BIND`).
pub fn place_words(id: u32) -> [u32; 2] {
    assert!(
        id < BIND,
        "binding id {id:#x} does not fit the svc immediate"
    );
    [SVC | ((BIND | id) << 5), RET]
}

/// Assembly for a page-aligned pool of `entries` thunks, symbol `atl_bind_pool`, section `.atl_thunks` (executable, not writable); slot k carries binding k.
/// Panics when an id does not fit the immediate.
pub fn pool_asm(entries: u32) -> String {
    let mut s = String::from(
        ".section .atl_thunks,\"ax\",@progbits\n.p2align 12\n.globl atl_bind_pool\n.type atl_bind_pool,@function\natl_bind_pool:\n",
    );
    for i in 0..entries {
        let [svc, ret] = place_words(i);
        writeln!(s, "    .inst {svc:#010x}\n    .inst {ret:#010x}").expect("writing to a String");
    }
    writeln!(s, ".size atl_bind_pool, . - atl_bind_pool").expect("writing to a String");
    s
}

/// Rust source of the host pool `POOL` (a [`Pool`] of `entries` thunks, page aligned, in `.rodata`): slot k is [`place_words`]`(k)`.
/// Included by the crate whose build.rs wrote it. Panics when `entries` exceeds the immediate's ids.
pub fn pool_rust(entries: u32) -> String {
    let mut s = format!(
        "// generated by atl-bridgegen::aarch64::pool_rust: do not edit\n\
         /// Binding thunks, page aligned: slot k = `svc #(BIND | k); ret`.\n\
         #[repr(C, align(4096))]\n\
         pub struct Pool(pub [[u32; 2]; {entries}]);\n\
         pub static POOL: Pool = Pool([\n"
    );
    for i in 0..entries {
        let [svc, ret] = place_words(i);
        writeln!(s, "    [{svc:#010x}, {ret:#010x}],").expect("writing to a String");
    }
    s.push_str("]);\n");
    s
}

/// Rust source of the host constants ([`SVC`], [`RET`], [`BIND`], [`PLACEHOLDER`]), so a crate that decodes or patches thunks uses the same values as the emitter.
pub fn constants_rust() -> String {
    format!(
        "// generated by atl-bridgegen::aarch64::constants_rust: do not edit\n\
         pub const SVC: u32 = {SVC:#x};\n\
         pub const RET: u32 = {RET:#x};\n\
         pub const BIND: u32 = {BIND:#x};\n\
         pub const PLACEHOLDER: [u32; 2] = [{:#x}, {:#x}];\n",
        PLACEHOLDER[0], PLACEHOLDER[1]
    )
}
