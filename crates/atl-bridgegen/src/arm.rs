//! arm (A32) guest thunks for the QEMU engine (phase 4 P4a), aarch64.rs's twin. A binding thunk is two A32 words, `svc #(BIND | id)` then `bx lr`: the svc imm24 carries the binding id, which atl-qemu-engine's trap decode reads (patch 0005 reads the Arm imm24 from the insn). A32, not Thumb: the NB placeholders the thunks replace are Arm-mode code (`target("arm")` stubs, vdso_arm.S), and a caller of either mode reaches a slot through `blx`, returning by `bx lr`.
//! Emitted forms as for aarch64: [`pool_rust`] for the host pool, [`constants_rust`] for the host constants.

use std::fmt::Write;

/// `svc #0`, A32 encoding A1 (Arm ARM: cond 1111 imm24), cond AL: imm24 at bits 23:0.
pub const SVC: u32 = 0xEF00_0000;
/// `bx lr`, A32 encoding A1 (cond 0001 0010 1111 1111 1111 0001 Rm), cond AL, Rm = r14.
pub const RET: u32 = 0xE12F_FF1E;
/// Bit 15 of the svc immediate: a binding, the low 15 bits the id (32768 bindings), as on aarch64. Far below the OABI syscall range 0x900000..0x9fffff, so no OABI number collides.
pub const BIND: u32 = 0x8000;
/// The placeholder body of an intercept stub as the NB sources ship it: `ldr r3, =0; bx r3` (interceptable_functions.h `__arm__`, vdso_arm.S), which the assembler emits as `mov r3, #0` (A32 MOV immediate A1: cond 0011 1010 0000 Rd imm12, Rd = r3) and `bx r3` (Rm = r3). In-place writes replace it.
pub const PLACEHOLDER: [u32; 2] = [0xE3A0_3000, 0xE12F_FF13];

/// The two words of binding `id`'s thunk. Panics when `id` does not fit the immediate (`id >= BIND`).
pub fn place_words(id: u32) -> [u32; 2] {
    assert!(
        id < BIND,
        "binding id {id:#x} does not fit the svc immediate"
    );
    [SVC | BIND | id, RET]
}

/// Rust source of the host pool words `ARM_POOL` (`entries` thunks, slot k = [`place_words`]`(k)`). Plain data: a 32-bit guest cannot reach a host static above 4 GiB, so the consumer copies it into a window (atl-qemu-engine `map_window`).
/// Included by the crate whose build.rs wrote it. Panics when `entries` exceeds the immediate's ids.
pub fn pool_rust(entries: u32) -> String {
    let mut s = format!(
        "// generated by atl-bridgegen::arm::pool_rust: do not edit\n\
         /// arm binding thunks: slot k = `svc #(BIND | k); bx lr`, copied into a guest window before use.\n\
         pub static ARM_POOL: [[u32; 2]; {entries}] = [\n"
    );
    for i in 0..entries {
        let [svc, ret] = place_words(i);
        writeln!(s, "    [{svc:#010x}, {ret:#010x}],").expect("writing to a String");
    }
    s.push_str("];\n");
    s
}

/// Rust source of the host constants ([`SVC`], [`RET`], [`BIND`], [`PLACEHOLDER`]) under `ARM_` names, beside aarch64's in one module.
pub fn constants_rust() -> String {
    format!(
        "// generated by atl-bridgegen::arm::constants_rust: do not edit\n\
         pub const ARM_SVC: u32 = {SVC:#x};\n\
         pub const ARM_RET: u32 = {RET:#x};\n\
         pub const ARM_BIND: u32 = {BIND:#x};\n\
         pub const ARM_PLACEHOLDER: [u32; 2] = [{:#x}, {:#x}];\n",
        PLACEHOLDER[0], PLACEHOLDER[1]
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Encodings assembled from the Arm ARM's A32 field layouts, independently of the constants: cond AL = 0b1110 in bits 31:28.
    #[test]
    fn encodings_follow_the_arm_arm() {
        const AL: u32 = 0b1110 << 28;
        // SVC A1: cond | 1111 (27:24) | imm24
        let svc = |imm: u32| AL | (0b1111 << 24) | imm;
        // BX A1: cond | 0001_0010 (27:20) | 1111_1111_1111 (19:8) | 0001 (7:4) | Rm
        let bx = |rm: u32| AL | (0b0001_0010 << 20) | (0xFFF << 8) | (0b0001 << 4) | rm;
        // MOV (immediate) A1: cond | 00 1 1101 S=0 (27:20 = 0011_1010) | Rn 0000 | Rd | imm12
        let mov_imm = |rd: u32, imm12: u32| AL | (0b0011_1010 << 20) | (rd << 12) | imm12;
        assert_eq!(place_words(0), [svc(0x8000), bx(14)]);
        assert_eq!(place_words(0x7fff), [svc(0xffff), bx(14)]);
        assert_eq!(PLACEHOLDER, [mov_imm(3, 0), bx(3)]);
    }

    #[test]
    #[should_panic(expected = "does not fit")]
    fn an_id_past_the_immediate_panics() {
        place_words(BIND);
    }
}
