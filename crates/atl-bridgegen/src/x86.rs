//! x86_64 entry shells, call pools and patch encodings of the identity engine (QEMU bridge plan Q5-7). Every byte is the ISA's: CALL rel32 `E8 cd`, MOVABS r64, imm64 `REX.W+B B8+rd io` (r10 `49 BA`, r11 `49 BB`), JMP r/m64 `FF /4` with REX.B (`jmp *%r11` = `41 FF E3`), UD2 `0F 0B`, INT3 `CC` (Intel SDM Vol. 2). tests/x86_words.rs checks each encoder against literals, never against the emitter.
//! Generated: the two entry shells, the two call pools they index, and the byte templates the engine copies and fills. Not generated: the FS-switch core (`atl_nb_up`, `atl_nb_call_guest`, `atl_nb_cross_to_guest*`, `atl_nb_signal_entry`), which stays hand-written in atl-native-bridge's `global_asm!`.
//! Two emitted forms: [`entries_asm`] (assembled into the engine's `global_asm!`) and [`constants_rust`] (the templates). build.rs writes both into OUT_DIR, so no crate depends on this one at run time.

use std::fmt::Write;

/// Opcode of `call rel32`.
pub const CALL_REL32: u8 = 0xE8;
/// Bytes of a `call rel32`: a pool call returns to slot + this, which the shell subtracts out.
pub const CALL_LEN: usize = 5;
/// Pool stride: the call padded to 8 (`.p2align 3`); `(return - (pool + CALL_LEN)) = slot * SLOT`.
pub const SLOT: usize = 8;
/// `movabs $imm64, %r10`: REX.W+B `49`, B8+2 `BA`.
pub const MOVABS_R10: [u8; 2] = [0x49, 0xBA];
/// `movabs $imm64, %r11`: REX.W+B `49`, B8+3 `BB`. Also the prefix of an unbound NBS interceptable stub (`movabs $0, %r11`).
pub const MOVABS_R11: [u8; 2] = [0x49, 0xBB];
/// `jmp *%r11`: REX.B `41`, FF /4, ModRM `E3` (mod 11, reg 100, rm 011).
pub const JMP_R11: [u8; 3] = [0x41, 0xFF, 0xE3];
/// `ud2`: the placeholder the NBS linker hook carries until `patch_hook` rewrites it.
pub const UD2: [u8; 2] = [0x0F, 0x0B];
/// `int3`: fill around a patch.
pub const INT3: u8 = 0xCC;
/// Length of [`jump`]: `movabs $imm64, %r11; jmp *%r11`.
pub const JUMP_LEN: usize = 13;
/// Offset of the imm64 in a [`jump`]; a stub's `movabs` immediate sits at the same offset.
pub const IMM_AT: usize = 2;
/// Length of [`down_stub`]: `movabs $target, %r10; movabs $entry, %r11; jmp *%r11; int3`.
pub const DOWN_LEN: usize = 24;
/// Offset of the target imm64 in a [`down_stub`].
pub const DOWN_TARGET_AT: usize = 2;
/// Offset of the entry imm64 in a [`down_stub`].
pub const DOWN_ENTRY_AT: usize = 12;

/// `movabs $target, %r11; jmp *%r11`: the stub jump a linker hook or NBS stub is rewritten to.
pub fn jump(target: u64) -> [u8; JUMP_LEN] {
    let mut b = [0; JUMP_LEN];
    b[..IMM_AT].copy_from_slice(&MOVABS_R11);
    b[IMM_AT..IMM_AT + 8].copy_from_slice(&target.to_le_bytes());
    b[IMM_AT + 8..].copy_from_slice(&JMP_R11);
    b
}

/// Host-to-guest down stub: `target` in %r10, `entry` (the crossing kind's) in %r11, then `jmp *%r11`.
pub fn down_stub(target: u64, entry: u64) -> [u8; DOWN_LEN] {
    let mut b = [INT3; DOWN_LEN];
    b[..DOWN_TARGET_AT].copy_from_slice(&MOVABS_R10);
    b[DOWN_TARGET_AT..DOWN_TARGET_AT + 8].copy_from_slice(&target.to_le_bytes());
    b[DOWN_ENTRY_AT - MOVABS_R11.len()..DOWN_ENTRY_AT].copy_from_slice(&MOVABS_R11);
    b[DOWN_ENTRY_AT..DOWN_ENTRY_AT + 8].copy_from_slice(&entry.to_le_bytes());
    b[DOWN_ENTRY_AT + 8..DOWN_ENTRY_AT + 8 + JMP_R11.len()].copy_from_slice(&JMP_R11);
    b
}

/// Rust source of the patch templates (`include!`d by the engine): `JUMP` and `DOWN` are [`jump`] / [`down_stub`] with zero immediates, which the engine copies and fills at `IMM_AT` / `DOWN_TARGET_AT` / `DOWN_ENTRY_AT`.
pub fn constants_rust() -> String {
    format!(
        "// generated by atl-bridgegen::x86::constants_rust: do not edit\n\
         /// Prefix of an unbound NBS interceptable stub (`movabs $_, %r11`); `is_stub` tests it.\n\
         pub const STUB_PREFIX: [u8; 2] = {};\n\
         /// Placeholder of an NBS linker hook: `ud2`, then int3 padding up to the next function.\n\
         pub const HOOK_PLACEHOLDER: [u8; 2] = {};\n\
         pub const INT3: u8 = {INT3:#04x};\n\
         /// Pool slot stride in bytes.\n\
         pub const SLOT: usize = {SLOT};\n\
         /// `movabs $imm64, %r11; jmp *%r11` with the imm64 zero (length {JUMP_LEN}); the engine copies it over a hook or stub and writes the target at `IMM_AT`.\n\
         pub const JUMP: [u8; {JUMP_LEN}] = {};\n\
         pub const JUMP_LEN: usize = {JUMP_LEN};\n\
         pub const IMM_AT: usize = {IMM_AT};\n\
         /// Down stub with zero immediates (length {DOWN_LEN}); the engine writes the target at `DOWN_TARGET_AT` and the entry at `DOWN_ENTRY_AT`.\n\
         pub const DOWN: [u8; {DOWN_LEN}] = {};\n\
         pub const DOWN_LEN: usize = {DOWN_LEN};\n\
         pub const DOWN_TARGET_AT: usize = {DOWN_TARGET_AT};\n\
         pub const DOWN_ENTRY_AT: usize = {DOWN_ENTRY_AT};\n",
        bytes_lit(&MOVABS_R11),
        bytes_lit(&UD2),
        bytes_lit(&jump(0)),
        bytes_lit(&down_stub(0, 0)),
    )
}

/// `[0x.., 0x..]`, lower-case hex, for the emitted templates.
fn bytes_lit(b: &[u8]) -> String {
    let items: Vec<String> = b.iter().map(|x| format!("{x:#04x}")).collect();
    format!("[{}]", items.join(", "))
}

/// Assembly for the identity engine's entry shells and call pools, `.text`, for its `global_asm!`.
/// `atl_nb_cross_to_host` (host-function slots) and `atl_nb_jni_up` (JNI slots) pop the return address, turn it into the slot's index (`ret - (pool + CALL_LEN)`), index their table and jump to the up crossing `atl_nb_up`. `atl_nb_jni_up` first rewrites %rdi to the host object (word 1 of the guest JNIEnv/JavaVM) and reads the target from that object's own table per call (ART swaps an env's table for CheckJNI); every other argument, %al and stack word reaches the host function untouched (variadic Call*Method).
/// `atl_nb_host_thunks` holds `thunks` slots and `atl_nb_jni_stubs` `jni_stubs`; each slot is `call` + alignment, written as opcode plus `.long target - . - 4` so the generator owns the displacement expression.
/// `disp_bias` is 0 in every shipped build. The break (build.rs `BREAKS`) sets it to 1: the displacement comes out one short, so each pool call lands one byte past its shell.
pub fn entries_asm(thunks: usize, jni_stubs: usize, disp_bias: usize) -> String {
    assert!(
        disp_bias < CALL_LEN - 1,
        "disp_bias {disp_bias} leaves no displacement end"
    );
    // bytes from the displacement field to the end of the call: `.` is the field's own address, one past the opcode
    let end = CALL_LEN - 1 - disp_bias;
    let mut s = String::from(".text\n");
    shell(
        &mut s,
        "atl_nb_cross_to_host",
        "atl_nb_host_thunks",
        &[
            "lea atl_nb_host_targets(%rip), %r10",
            "mov (%r10,%r11), %r11",
        ],
    );
    shell(
        &mut s,
        "atl_nb_jni_up",
        "atl_nb_jni_stubs",
        &[
            "mov 8(%rdi), %rdi",
            "mov (%rdi), %r10",
            "mov (%r10,%r11), %r11",
        ],
    );
    pool(
        &mut s,
        "atl_nb_host_thunks",
        "atl_nb_cross_to_host",
        thunks,
        end,
    );
    pool(&mut s, "atl_nb_jni_stubs", "atl_nb_jni_up", jni_stubs, end);
    s
}

/// One index shell: `pop` the return, subtract the pool base + [`CALL_LEN`] (the return of a pool call), then `body` (loads the target into %r11, may first rewrite %rdi), then the up crossing.
fn shell(s: &mut String, name: &str, pool: &str, body: &[&str]) {
    write!(
        s,
        ".globl {name}\n.type {name},@function\n{name}:\n    pop %r11\n    lea {pool}+{CALL_LEN}(%rip), %r10\n    sub %r10, %r11\n"
    )
    .expect("writing to a String");
    for line in body {
        writeln!(s, "    {line}").expect("writing to a String");
    }
    write!(s, "    jmp atl_nb_up\n.size {name}, .-{name}\n").expect("writing to a String");
}

/// A pool of `slots` calls to `target`, one per [`SLOT`] bytes. Slot k's displacement is `target - (slot + 5)`, written as `target - . - end`.
fn pool(s: &mut String, name: &str, target: &str, slots: usize, end: usize) {
    write!(s, ".p2align 3\n.globl {name}\n{name}:\n").expect("writing to a String");
    for _ in 0..slots {
        write!(
            s,
            "    .byte {CALL_REL32:#04x}\n    .long {target} - . - {end}\n    .p2align 3\n"
        )
        .expect("writing to a String");
    }
}
