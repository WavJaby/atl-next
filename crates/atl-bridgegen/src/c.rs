//! Backend: a C header declaring a chosen part of an interface for code built against another C library
//! (bionic-only API for glibc builds). Prints the functions and constants asked for, the interface's
//! typedefs and forward declarations they use, and the standard headers their other types come from --
//! none of the source's own includes or `sys/cdefs.h` macros unless the caller keeps them (`Kept`: an
//! API whose callers rely on what its header brings in). Needs no include at all when only builtin types
//! are used and nothing is kept, so such a header can be force-included without running libc headers
//! early.

use std::collections::BTreeSet;
use std::fmt::Write;

use anyhow::{Context, Result, bail};

use crate::ir::{ArchView, Constant, Interface, Nullability, RecordKind, Ty};

/// Standard C / POSIX typedef names and the header that declares each; the printer includes these
/// instead of the source's own includes. A typedef from outside the interface that is not listed fails.
const STD_TYPEDEFS: &[(&str, &str)] = &[
    ("size_t", "stddef.h"),
    ("ptrdiff_t", "stddef.h"),
    ("wchar_t", "stddef.h"),
    ("int8_t", "stdint.h"),
    ("int16_t", "stdint.h"),
    ("int32_t", "stdint.h"),
    ("int64_t", "stdint.h"),
    ("uint8_t", "stdint.h"),
    ("uint16_t", "stdint.h"),
    ("uint32_t", "stdint.h"),
    ("uint64_t", "stdint.h"),
    ("intptr_t", "stdint.h"),
    ("uintptr_t", "stdint.h"),
    ("intmax_t", "stdint.h"),
    ("uintmax_t", "stdint.h"),
    ("ssize_t", "sys/types.h"),
    ("off_t", "sys/types.h"),
    ("off64_t", "sys/types.h"),
    ("pid_t", "sys/types.h"),
    ("uid_t", "sys/types.h"),
    ("gid_t", "sys/types.h"),
    ("mode_t", "sys/types.h"),
    ("va_list", "stdarg.h"),
    ("FILE", "stdio.h"),
];

/// What a printed header keeps of its source as written, for callers relying on it.
#[derive(Default)]
pub struct Kept<'a> {
    /// The source's own `<…>` includes, in its order (`async_safe/log.h` -> `android/log.h`, whose
    /// `ANDROID_LOG_*` its callers pass); a `"…"` include fails (a file of the source's, not API).
    pub includes: bool,
    /// Function-like macros of the source (`async_safe_fatal`), printed as it defines them.
    pub macros: &'a [&'a str],
}

/// The header text: `functions` and `constants` (integer or string macros, enumerators) of `arch`'s view,
/// and what `kept` keeps of the source.
pub fn header(
    iface: &Interface,
    arch: &str,
    functions: &[&str],
    constants: &[&str],
    kept: &Kept,
) -> Result<String> {
    let view = iface
        .arches
        .get(arch)
        .with_context(|| format!("{}: no view for {arch}", iface.name))?;
    let mut p = Printer {
        view,
        includes: BTreeSet::new(),
        typedefs: Vec::new(),
        forwards: BTreeSet::new(),
    };
    let mut decls = String::new();
    for f in functions {
        let sig = view
            .functions
            .get(*f)
            .with_context(|| format!("{}: no function {f}", iface.header))?;
        let text = p
            .decl(&Ty::Function(Box::new(sig.clone())), false, f)
            .with_context(|| (*f).to_owned())?;
        writeln!(decls, "{text};")?;
    }
    let mut defines = String::new();
    for c in constants {
        let value = match (view.constants.get(*c), view.strings.get(*c)) {
            (Some(k), _) => literal(k).with_context(|| (*c).to_owned())?,
            (None, Some(s)) => string_literal(s),
            (None, None) => bail!("{}: no constant {c}", iface.header),
        };
        writeln!(defines, "#define {c} {value}")?;
    }
    for m in kept.macros {
        let def = view
            .function_macros
            .get(*m)
            .with_context(|| format!("{}: no function-like macro {m}", iface.header))?;
        writeln!(defines, "#define {def}")?;
    }

    let mut out = format!(
        "// generated by atl-bridgegen from {} for {arch} ({}), do not edit\n#pragma once\n",
        iface.header, view.triple
    );
    let mut includes: Vec<&str> = Vec::new();
    if kept.includes {
        for i in &view.includes {
            let name = i
                .strip_prefix('<')
                .and_then(|i| i.strip_suffix('>'))
                .with_context(|| format!("{}: kept include {i} is not <…>", iface.header))?;
            includes.push(name);
        }
    }
    let own: Vec<&str> = p
        .includes
        .iter()
        .copied()
        .filter(|i| !includes.contains(i))
        .collect();
    includes.extend(own);
    if !includes.is_empty() {
        out.push('\n');
        for i in includes {
            writeln!(out, "#include <{i}>")?;
        }
    }
    out.push_str("\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n");
    // `typedef struct x x;` declares `struct x` itself
    let typedef_records: BTreeSet<&str> = p
        .typedefs
        .iter()
        .filter_map(|t| match t.target.resolved() {
            Ty::Opaque { name, .. } => Some(name.as_str()),
            _ => None,
        })
        .collect();
    let forwards: Vec<&(RecordKind, String)> = p
        .forwards
        .iter()
        .filter(|(_, n)| !typedef_records.contains(n.as_str()))
        .collect();
    if !p.typedefs.is_empty() || !forwards.is_empty() {
        out.push('\n');
    }
    for (kind, name) in forwards {
        writeln!(out, "{} {name};", keyword(*kind))?;
    }
    for t in &p.typedefs {
        writeln!(out, "{}", t.text)?;
    }
    if !defines.is_empty() {
        out.push('\n');
        out.push_str(&defines);
    }
    if !decls.is_empty() {
        out.push('\n');
        out.push_str(&decls);
    }
    out.push_str("\n#ifdef __cplusplus\n}\n#endif\n");
    Ok(out)
}

struct Printer<'a> {
    view: &'a ArchView,
    /// Standard headers the printed types need.
    includes: BTreeSet<&'static str>,
    /// Interface typedefs, dependencies before users.
    typedefs: Vec<Typedef>,
    /// Records used behind pointers, declared incomplete.
    forwards: BTreeSet<(RecordKind, String)>,
}

struct Typedef {
    name: String,
    /// `typedef …;`
    text: String,
    target: Ty,
}

impl Printer<'_> {
    /// `ty` declaring `inner` (a name, or a declarator built so far); `konst`: the type itself is const.
    fn decl(&mut self, ty: &Ty, konst: bool, inner: &str) -> Result<String> {
        let base = |s: &str| words(&[if konst { "const" } else { "" }, s, inner]);
        Ok(match ty {
            Ty::Typedef { name, ty: target } => {
                self.typedef(name, target)?;
                base(name)
            }
            Ty::Void => base("void"),
            Ty::Bool => {
                self.includes.insert("stdbool.h");
                base("bool")
            }
            Ty::Int { c, .. } => base(c.c_name()),
            Ty::Float { bits } => {
                bail!("{bits}-bit float: the C printer does not name float types yet")
            }
            Ty::Opaque { name, record: kind } => {
                self.forwards.insert((*kind, name.clone()));
                base(&format!("{} {name}", keyword(*kind)))
            }
            Ty::Record { name } => {
                bail!("record {name} by value: the C printer declares records only behind pointers")
            }
            Ty::Pointer {
                pointee,
                is_const,
                nullability,
                ..
            } => {
                let null = match nullability {
                    Nullability::NonNull => "_Nonnull",
                    Nullability::Nullable => "_Nullable",
                    Nullability::Unspecified => "",
                };
                let ptr = words(&["*", if konst { "const" } else { "" }, null, inner]);
                let ptr = if matches!(pointee.as_ref(), Ty::Function(_) | Ty::Array { .. }) {
                    format!("({ptr})")
                } else {
                    ptr
                };
                // a pointer to an interface record names it incomplete
                if let Ty::Record { name } = pointee.as_ref() {
                    let kind = self
                        .view
                        .records
                        .get(name)
                        .map_or(RecordKind::Struct, |r| r.kind);
                    self.forwards.insert((kind, name.clone()));
                    return Ok(words(&[
                        if *is_const { "const" } else { "" },
                        &format!("{} {name}", keyword(kind)),
                        &ptr,
                    ]));
                }
                self.decl(pointee, *is_const, &ptr)?
            }
            Ty::Function(sig) => {
                let mut params = sig
                    .params
                    .iter()
                    .map(|p| self.decl(p, false, ""))
                    .collect::<Result<Vec<_>>>()?;
                if sig.variadic {
                    params.push("...".to_owned());
                }
                let params = if params.is_empty() {
                    "void".to_owned()
                } else {
                    params.join(", ")
                };
                self.decl(&sig.ret, false, &format!("{inner}({params})"))?
            }
            Ty::Array { elem, len } => self.decl(elem, konst, &format!("{inner}[{len}]"))?,
        })
    }

    /// Records the typedef `name`: declared by the interface -> printed once; else a standard header.
    fn typedef(&mut self, name: &str, target: &Ty) -> Result<()> {
        if self.typedefs.iter().any(|t| t.name == name) {
            return Ok(());
        }
        if self.view.typedefs.contains_key(name) {
            // typedefs the target uses come out first
            let text = format!("typedef {};", self.decl(target, false, name)?);
            self.typedefs.push(Typedef {
                name: name.to_owned(),
                text,
                target: target.clone(),
            });
            return Ok(());
        }
        let header = STD_TYPEDEFS
            .iter()
            .find(|(n, _)| *n == name)
            .map(|(_, h)| *h)
            .with_context(|| format!("typedef {name} comes from outside the interface and is not a standard type (STD_TYPEDEFS)"))?;
        self.includes.insert(header);
        Ok(())
    }
}

fn keyword(kind: RecordKind) -> &'static str {
    match kind {
        RecordKind::Struct => "struct",
        RecordKind::Union => "union",
    }
}

/// Non-empty words joined by single spaces.
fn words(parts: &[&str]) -> String {
    parts
        .iter()
        .filter(|w| !w.is_empty())
        .copied()
        .collect::<Vec<_>>()
        .join(" ")
}

/// The constant as a C literal of its own type.
fn literal(c: &Constant) -> Result<String> {
    let Ty::Int {
        bits,
        signed,
        c: cint,
    } = c.ty
    else {
        bail!("constant of non-integer type {:?}", c.ty);
    };
    // types without a suffix are narrower than int and promote to it in any expression
    let suffix = cint.literal_suffix().unwrap_or("");
    if !signed {
        return Ok(format!("{}{suffix}", c.bits));
    }
    let shift = 64 - bits;
    let v = ((c.bits << shift) as i64) >> shift;
    Ok(if v < 0 {
        format!("({v}{suffix})")
    } else {
        format!("{v}{suffix}")
    })
}

fn string_literal(s: &str) -> String {
    let mut out = String::from("\"");
    for b in s.bytes() {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            0x20..=0x7e => out.push(b as char),
            _ => out.push_str(&format!("\\{b:03o}")),
        }
    }
    out.push('"');
    out
}
