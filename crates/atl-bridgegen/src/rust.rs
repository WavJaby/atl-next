//! Rust backends for one host arch. A header change that moves a field or changes a signature fails the
//! build, not a run.
//! - `host_module`: `#[repr(C)]` types, each with compile-time asserts that rustc's layout equals clang's.
//! - `api_module`: the constants, opaque types and records (as `host_module`'s) of an API we implement,
//!   and a check that each implementing function has exactly the header's signature.
//! - `layout_module`: size, alignment and field offsets as constants, for code that reads a layout in
//!   shared memory through atomics rather than through a Rust type.
//! - `resolver_module`: exported shells with the header's signatures that forward to an implementation looked up by name at run time.
//! - `import_module`: `api_module`'s types with the header's fn-pointer type per function, for a caller that looks the functions up itself.

use std::collections::BTreeSet;
use std::fmt::Write;

use anyhow::{Context, Result, bail, ensure};

use crate::ir::{ArchView, Constant, Interface, Nullability, Record, RecordKind, Signature, Ty};

/// Rust keywords that can appear as C identifiers; emitted as raw identifiers.
const KEYWORDS: &[&str] = &[
    "as", "async", "await", "box", "break", "const", "continue", "crate", "dyn", "else", "enum",
    "extern", "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod",
    "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe",
    "use", "where", "while", "yield",
];

fn view<'a>(iface: &'a Interface, arch: &str) -> Result<&'a ArchView> {
    iface
        .arches
        .get(arch)
        .with_context(|| format!("{}: no view for {arch}", iface.name))
}

fn banner(iface: &Interface, arch: &str, view: &ArchView) -> String {
    format!(
        "// generated by atl-bridgegen from {} for {arch} ({}), do not edit\n\n",
        iface.header, view.triple
    )
}

/// The module text for `arch` (a host arch of the interface).
pub fn host_module(iface: &Interface, arch: &str) -> Result<String> {
    let view = view(iface, arch)?;
    let mut out = banner(iface, arch, view);
    let mut opaque = BTreeSet::new();
    constants(&mut out, view, &mut opaque)?;
    for (name, record) in &view.records {
        record_item(&mut out, name, record, &mut opaque)?;
    }
    opaque_types(&mut out, view, &opaque)?;
    Ok(out)
}

/// `#[repr(C)]` type of `record` with asserts that rustc's layout equals clang's.
fn record_item(
    out: &mut String,
    name: &str,
    record: &Record,
    opaque: &mut BTreeSet<String>,
) -> Result<()> {
    // rustc's own layout rules would give natural alignment; clang's attributes are carried over
    // and the asserts below prove the result
    let repr = if record.packed {
        format!("C, packed({})", record.align)
    } else if record.aligned {
        format!("C, align({})", record.align)
    } else {
        "C".to_owned()
    };
    let keyword = match record.kind {
        RecordKind::Struct => "struct",
        RecordKind::Union => "union",
    };
    writeln!(
        out,
        "#[repr({repr})]\n#[derive(Clone, Copy)]\n#[allow(non_camel_case_types, non_snake_case, dead_code)]\npub {keyword} {} {{",
        ident(name)
    )?;
    for f in &record.fields {
        let ty = rust_ty(&f.ty, opaque).with_context(|| format!("{name}.{}", f.name))?;
        writeln!(out, "    pub {}: {ty},", ident(&f.name))?;
    }
    writeln!(out, "}}")?;
    let n = ident(name);
    writeln!(
        out,
        "const _: () = assert!(::core::mem::size_of::<{n}>() == {});",
        record.size
    )?;
    writeln!(
        out,
        "const _: () = assert!(::core::mem::align_of::<{n}>() == {});",
        record.align
    )?;
    for f in &record.fields {
        writeln!(
            out,
            "const _: () = assert!(::core::mem::offset_of!({n}, {}) == {});",
            ident(&f.name),
            f.offset
        )?;
    }
    writeln!(out)?;
    Ok(())
}

/// Records of the interface `ty` uses, by value or behind pointers, and those their fields use, into `out`.
fn records_used(view: &ArchView, ty: &Ty, out: &mut BTreeSet<String>) {
    match ty {
        Ty::Record { name } => {
            if out.insert(name.clone())
                && let Some(r) = view.records.get(name)
            {
                for f in &r.fields {
                    records_used(view, &f.ty, out);
                }
            }
        }
        Ty::Typedef { ty, .. } => records_used(view, ty, out),
        Ty::Pointer { pointee, .. } => records_used(view, pointee, out),
        Ty::Array { elem, .. } => records_used(view, elem, out),
        Ty::Function(sig) => {
            for t in sig.params.iter().chain(std::iter::once(&sig.ret)) {
                records_used(view, t, out);
            }
        }
        _ => {}
    }
}

/// Constants, opaque types, and the records `functions` and the typedefs `types` use, of `arch`'s view
/// (`types`: what the printed C header defines besides, so both sides check the same layouts); and for
/// each of `functions` a check that `<implementation>::<function>` has the header's signature exactly:
/// a fn item coerces to the header's fn-pointer type only then. A C++ namespace is a module of the same path (`android::f` -> `<implementation>::android::f`).
pub fn api_module(
    iface: &Interface,
    arch: &str,
    functions: &[&str],
    types: &[&str],
    implementation: &str,
) -> Result<String> {
    functions_module(iface, arch, functions, types, &|f, ty| {
        let path: Vec<String> = f.split("::").map(ident).collect();
        format!("const _: {ty} = {implementation}::{};", path.join("::"))
    })
}

/// A record of function pointers we fill (a vtable handed out by a loader function, such as IMapper.h's `AIMapperV5`): the entry shells are generated from the header.
pub struct Table<'a> {
    /// The record; each of its fields is a pointer to a function, or named in `values`.
    pub record: &'a str,
    /// Rust path of the implementation: `<implementation>::<field>` is an `unsafe fn` of the field's exact signature (the compiler checks it where the shell calls it).
    pub implementation: &'a str,
    /// What a panic in the implementation answers, as a Rust expression of the field's return type: (field, return type). Not asked for a field that returns void.
    pub on_panic: &'a dyn Fn(&str, &Ty) -> Result<String>,
    /// (field, Rust expression) for the record's data fields (NativeBridgeCallbacks' `version`): `shells()` sets them so. A data field not named here is refused, as is a name that is no data field.
    pub values: &'a [(&'a str, &'a str)],
}

/// `api_module`, plus for `table` one exported-by-pointer `unsafe extern "C"` shell per function-pointer field with the header's exact signature, and `impl <record> { pub const fn shells() -> Self }` with every such field set to its shell, every data field to its `values` expression.
/// A shell calls the implementation with its arguments unchanged inside `catch_unwind` (a Rust panic must not cross into a C++ caller): a panic answers `on_panic`. Raw-pointer-to-safe-type conversion is the implementation's, at its first line (the thin-shell pattern).
/// The record must be reached by `functions` or `types` (so its layout is asserted); a variadic entry has no shell.
pub fn api_module_with_table(
    iface: &Interface,
    arch: &str,
    functions: &[&str],
    types: &[&str],
    implementation: &str,
    table: &Table<'_>,
) -> Result<String> {
    let mut out = api_module(iface, arch, functions, types, implementation)?;
    let record = view(iface, arch)?
        .records
        .get(table.record)
        .with_context(|| format!("{}: no record {}", iface.header, table.record))?;
    ensure!(
        out.contains(&format!("pub struct {} {{", ident(table.record))),
        "{}: not reached by `functions` or `types`, so its layout is not asserted",
        table.record
    );
    let mut opaque = BTreeSet::new();
    let mut entries = Vec::new();
    let mut valued = 0;
    for field in &record.fields {
        let f = field.name.as_str();
        let sig = match field.ty.resolved() {
            Ty::Pointer { pointee, .. } => match pointee.resolved() {
                Ty::Function(sig) => Some(sig),
                _ => None,
            },
            _ => None,
        };
        let Some(sig) = sig else {
            let (_, value) = table
                .values
                .iter()
                .find(|(n, _)| *n == f)
                .with_context(|| {
                    format!("{}.{f}: not a function pointer and no value", table.record)
                })?;
            entries.push(format!("            {}: {value},", ident(f)));
            valued += 1;
            continue;
        };
        ensure!(
            !sig.variadic,
            "{}.{f}: a variadic function cannot be forwarded",
            table.record
        );
        let params = sig
            .params
            .iter()
            .enumerate()
            .map(|(i, p)| Ok(format!("p{i}: {}", rust_ty(p, &mut opaque)?)))
            .collect::<Result<Vec<_>>>()
            .with_context(|| f.to_owned())?;
        let args = (0..sig.params.len())
            .map(|i| format!("p{i}"))
            .collect::<Vec<_>>()
            .join(", ");
        let call = format!(
            "unsafe {{ {}::{}({args}) }}",
            table.implementation,
            ident(f)
        );
        let (ret, body) = match sig.ret.resolved() {
            Ty::Void => (
                String::new(),
                format!(
                    "let _ = ::std::panic::catch_unwind(::std::panic::AssertUnwindSafe(|| {call}));"
                ),
            ),
            _ => {
                let fallback = (table.on_panic)(f, &sig.ret).with_context(|| f.to_owned())?;
                (
                    format!(" -> {}", rust_ty(&sig.ret, &mut opaque)?),
                    format!(
                        "::std::panic::catch_unwind(::std::panic::AssertUnwindSafe(|| {call})).unwrap_or_else(|_| {fallback})"
                    ),
                )
            }
        };
        let shell = format!("shell_{f}");
        writeln!(
            out,
            "#[allow(non_snake_case)]\nunsafe extern \"C\" fn {shell}({params}){ret} {{\n    // SAFETY: the implementation of `{f}`, of this exact signature (the compiler checks the call); the caller's contract is its own\n    {body}\n}}\n",
            params = params.join(", "),
        )?;
        entries.push(format!("            {}: Some({shell}),", ident(f)));
    }
    ensure!(
        valued == table.values.len(),
        "{}: `values` names a field that is no data field of the record",
        table.record
    );
    // the record's own fields already brought their opaque types into `out` (record_item -> opaque_types)
    opaque.retain(|o| !out.contains(&format!("pub struct {} {{", ident(o))));
    ensure!(
        opaque.is_empty(),
        "{}: entries use types the functions do not define: {opaque:?}",
        table.record
    );
    writeln!(
        out,
        "impl {} {{\n    /// Every entry set to its generated shell.\n    pub const fn shells() -> Self {{\n        Self {{\n{}\n        }}\n    }}\n}}",
        ident(table.record),
        entries.join("\n")
    )?;
    Ok(out)
}

/// `api_module` for an API we call through pointers looked up at run time (`dlsym`), not implement: for each of `functions` (C names) a type alias of that name, the header's fn-pointer type, instead of the implementation check.
/// Nothing is exported: unlike `resolver_module`'s shells, no symbol of the importing object can interpose on the library's.
/// A function named as a record of the interface (C's separate tag namespace: `int sigaction(int, const struct sigaction*, ...)`) gets the alias `<name>_fn`: both would be Rust types of one name.
pub fn import_module(
    iface: &Interface,
    arch: &str,
    functions: &[&str],
    types: &[&str],
) -> Result<String> {
    let records = &view(iface, arch)?.records;
    functions_module(iface, arch, functions, types, &|f, ty| {
        let name = if records.contains_key(f) {
            format!("{f}_fn")
        } else {
            f.to_owned()
        };
        format!(
            "#[allow(non_camel_case_types)]\npub type {} = {ty};",
            ident(&name)
        )
    })
}

/// Constants, opaque types, the records `functions` and the typedefs `types` use, and per function `item(name, fn-pointer type)`.
fn functions_module(
    iface: &Interface,
    arch: &str,
    functions: &[&str],
    types: &[&str],
    item: &dyn Fn(&str, &str) -> String,
) -> Result<String> {
    let view = view(iface, arch)?;
    let mut out = banner(iface, arch, view);
    let mut opaque = BTreeSet::new();
    constants(&mut out, view, &mut opaque)?;
    let mut records = BTreeSet::new();
    for f in functions {
        let sig = view
            .functions
            .get(*f)
            .with_context(|| format!("{}: no function {f}", iface.header))?;
        records_used(view, &Ty::Function(Box::new(sig.clone())), &mut records);
    }
    // a typedef, else a record tag (C++ `struct NativeBridgeCallbacks`, no typedef)
    for t in types {
        let ty = match view.typedefs.get(*t) {
            Some(ty) => ty.clone(),
            None if view.records.contains_key(*t) => Ty::Record {
                name: (*t).to_owned(),
            },
            None => bail!("{}: no typedef or record {t}", iface.header),
        };
        records_used(view, &ty, &mut records);
    }
    for name in &records {
        let record = view
            .records
            .get(name)
            .with_context(|| format!("{}: no record {name}", iface.header))?;
        record_item(&mut out, name, record, &mut opaque)?;
    }
    for f in functions {
        let sig = view
            .functions
            .get(*f)
            .with_context(|| format!("{}: no function {f}", iface.header))?;
        let ty = fn_ty(sig, &mut opaque).with_context(|| (*f).to_owned())?;
        writeln!(out, "{}", item(f, &ty))?;
        // `usize` / `isize` stand for these typedefs only where their width is the pointer's
        let mut sized = BTreeSet::new();
        for t in sig.params.iter().chain(std::iter::once(&sig.ret)) {
            pointer_sized_uses(t, &mut sized);
        }
        for (name, bits) in sized {
            writeln!(
                out,
                "const _: () = assert!(::core::mem::size_of::<usize>() * 8 == {bits}, \"{name}\");"
            )?;
        }
    }
    if !functions.is_empty() {
        writeln!(out)?;
    }
    opaque_types(&mut out, view, &opaque)?;
    Ok(out)
}

/// For each of `functions`, an exported `#[no_mangle]` shell with the header's exact signature that forwards its arguments unchanged to the implementation `resolver` finds by name: `<resolver>::<F>(c"<name>")`, an `unsafe fn(&CStr) -> Option<F>` the crate provides (F = the header's fn-pointer type), called once per function and process (`OnceLock`, so concurrent first calls are safe), its answer kept, `None` included.
/// Without an implementation the shell runs `on_null(name, return type)`, a diverging Rust expression (`return <value of the return type>`, or a call returning `!`): the caller decides what "no implementation" means for its API.
/// Opaque types the signatures use are defined; the module holds nothing else. A variadic function has no forwarding shell: fails.
pub fn resolver_module(
    iface: &Interface,
    arch: &str,
    functions: &[&str],
    resolver: &str,
    on_null: &dyn Fn(&str, &Ty) -> Result<String>,
) -> Result<String> {
    let view = view(iface, arch)?;
    let mut out = banner(iface, arch, view);
    let mut opaque = BTreeSet::new();
    for f in functions {
        let sig = view
            .functions
            .get(*f)
            .with_context(|| format!("{}: no function {f}", iface.header))?;
        ensure!(
            !sig.variadic,
            "{f}: a variadic function cannot be forwarded"
        );
        // a forwarded record is only ever behind a pointer: no layout to assert, it is opaque here
        for t in sig.params.iter().chain(std::iter::once(&sig.ret)) {
            ensure!(
                !matches!(t.resolved(), Ty::Record { .. }),
                "{f}: a record by value (its layout would need asserting; host_module types)"
            );
            pointed_records(t, &mut opaque);
        }
        let ty = fn_ty(sig, &mut opaque).with_context(|| (*f).to_owned())?;
        let params = sig
            .params
            .iter()
            .enumerate()
            .map(|(i, p)| Ok(format!("p{i}: {}", rust_ty(p, &mut opaque)?)))
            .collect::<Result<Vec<_>>>()
            .with_context(|| (*f).to_owned())?;
        let args: Vec<String> = (0..sig.params.len()).map(|i| format!("p{i}")).collect();
        let ret = match sig.ret.resolved() {
            Ty::Void => String::new(),
            _ => format!(" -> {}", rust_ty(&sig.ret, &mut opaque)?),
        };
        let fallback = on_null(f, &sig.ret).with_context(|| (*f).to_owned())?;
        writeln!(
            out,
            "#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}({params}){ret} {{\n    type F = {ty};\n    static IMPL: ::std::sync::OnceLock<Option<F>> = ::std::sync::OnceLock::new();\n    // SAFETY: F is the header's signature of `{f}`, the name looked up\n    let found = *IMPL.get_or_init(|| unsafe {{ {resolver}::<F>(c\"{f}\") }});\n    let Some(f) = found else {{ {fallback} }};\n    // SAFETY: the implementation of `{f}`, of this exact signature; the caller's contract is its own\n    unsafe {{ f({args}) }}\n}}\n",
            name = ident(f),
            params = params.join(", "),
            args = args.join(", "),
        )?;
        // `usize` / `isize` stand for these typedefs only where their width is the pointer's
        let mut sized = BTreeSet::new();
        for t in sig.params.iter().chain(std::iter::once(&sig.ret)) {
            pointer_sized_uses(t, &mut sized);
        }
        for (name, bits) in sized {
            writeln!(
                out,
                "const _: () = assert!(::core::mem::size_of::<usize>() * 8 == {bits}, \"{name}\");"
            )?;
        }
    }
    for name in &opaque {
        writeln!(
            out,
            "/// Only used behind pointers here.\n#[repr(C)]\n#[allow(non_camel_case_types)]\npub struct {} {{\n    _opaque: [u8; 0],\n}}\n",
            ident(name)
        )?;
    }
    Ok(out)
}

/// Records of this interface that `ty` reaches through pointers, into `out`.
fn pointed_records(ty: &Ty, out: &mut BTreeSet<String>) {
    match ty {
        Ty::Record { name } => {
            out.insert(name.clone());
        }
        Ty::Typedef { ty, .. } => pointed_records(ty, out),
        Ty::Pointer { pointee, .. } => pointed_records(pointee, out),
        Ty::Array { elem, .. } => pointed_records(elem, out),
        Ty::Function(sig) => {
            for t in sig.params.iter().chain(std::iter::once(&sig.ret)) {
                pointed_records(t, out);
            }
        }
        _ => {}
    }
}

/// Constants, and per record a module `<record>` with `SIZE`, `ALIGN` and one `usize` offset per field
/// (an anonymous member's record is `<record>_anon<i>`, offsets relative to it).
pub fn layout_module(iface: &Interface, arch: &str) -> Result<String> {
    let view = view(iface, arch)?;
    let mut out = banner(iface, arch, view);
    constants(&mut out, view, &mut BTreeSet::new())?;
    for (name, record) in &view.records {
        writeln!(
            out,
            "/// `{name}` as clang lays it out.\n#[allow(non_snake_case, non_upper_case_globals, dead_code)]\npub mod {} {{\n    pub const SIZE: usize = {};\n    pub const ALIGN: usize = {};",
            ident(name),
            record.size,
            record.align
        )?;
        for f in &record.fields {
            ensure!(
                f.name != "SIZE" && f.name != "ALIGN",
                "{name}.{}: field name collides with the layout constants",
                f.name
            );
            writeln!(
                out,
                "    pub const {}: usize = {};",
                ident(&f.name),
                f.offset
            )?;
        }
        writeln!(out, "}}\n")?;
    }
    Ok(out)
}

fn constants(out: &mut String, view: &ArchView, opaque: &mut BTreeSet<String>) -> Result<()> {
    for (name, c) in &view.constants {
        writeln!(
            out,
            "#[allow(non_upper_case_globals, dead_code)]\npub const {}: {} = {};",
            const_ident(name),
            rust_ty(&c.ty, opaque).with_context(|| name.clone())?,
            literal(c)?
        )?;
    }
    for (name, s) in &view.strings {
        writeln!(
            out,
            "#[allow(non_upper_case_globals, dead_code)]\npub const {}: &str = {s:?};",
            const_ident(name)
        )?;
    }
    if !view.constants.is_empty() || !view.strings.is_empty() {
        writeln!(out)?;
    }
    Ok(())
}

fn opaque_types(out: &mut String, view: &ArchView, opaque: &BTreeSet<String>) -> Result<()> {
    for name in opaque.iter().filter(|o| !view.records.contains_key(*o)) {
        writeln!(
            out,
            "/// Defined outside this interface; only used behind pointers.\n#[repr(C)]\n#[allow(non_camel_case_types)]\npub struct {} {{\n    _opaque: [u8; 0],\n}}\n",
            ident(name)
        )?;
    }
    Ok(())
}

/// The constant's value as a Rust literal of its type.
fn literal(c: &Constant) -> Result<String> {
    let Ty::Int { bits, signed, .. } = c.ty else {
        bail!("constant of non-integer type {:?}", c.ty);
    };
    if !signed {
        return Ok(c.bits.to_string());
    }
    // sign-extend from the type's width
    let shift = 64 - bits;
    Ok((((c.bits << shift) as i64) >> shift).to_string())
}

fn ident(name: &str) -> String {
    if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

/// A constant's Rust name: a C++ class member `rec::name` becomes `rec_name`.
fn const_ident(name: &str) -> String {
    ident(&name.replace("::", "_"))
}

/// C typedefs of pointer width, printed as Rust's pointer-sized integers (an implementation then writes
/// `usize`, not a width); unsigned ones as `usize`, signed as `isize`. A record using one keeps its
/// layout asserts, a signature gets a width assert (`api_module`).
const POINTER_SIZED: &[&str] = &["size_t", "ssize_t", "ptrdiff_t", "intptr_t", "uintptr_t"];

/// The `POINTER_SIZED` typedefs `ty` uses, with their C width, into `out`.
fn pointer_sized_uses<'t>(ty: &'t Ty, out: &mut BTreeSet<(&'t str, u32)>) {
    match ty {
        Ty::Typedef { name, ty } => match ty.resolved() {
            Ty::Int { bits, .. } if POINTER_SIZED.contains(&name.as_str()) => {
                out.insert((name, *bits));
            }
            _ => pointer_sized_uses(ty, out),
        },
        Ty::Pointer { pointee, .. } => pointer_sized_uses(pointee, out),
        Ty::Array { elem, .. } => pointer_sized_uses(elem, out),
        Ty::Function(sig) => {
            for t in sig.params.iter().chain(std::iter::once(&sig.ret)) {
                pointer_sized_uses(t, out);
            }
        }
        _ => {}
    }
}

fn rust_ty(ty: &Ty, opaque: &mut BTreeSet<String>) -> Result<String> {
    Ok(match ty {
        // a parameter only (a va_list field or return has no FFI meaning): Rust's own va_list ABI type
        Ty::Typedef { name, .. } if name == "va_list" => "::core::ffi::VaList<'_>".to_owned(),
        Ty::Typedef { name, ty } if POINTER_SIZED.contains(&name.as_str()) => match ty.resolved() {
            Ty::Int { signed: false, .. } => "usize".to_owned(),
            Ty::Int { signed: true, .. } => "isize".to_owned(),
            _ => rust_ty(ty, opaque)?,
        },
        Ty::Typedef { ty, .. } => rust_ty(ty, opaque)?,
        Ty::Void => "::core::ffi::c_void".to_owned(),
        Ty::Bool => "bool".to_owned(),
        Ty::Int { bits, signed, .. } => match (bits, signed) {
            (8 | 16 | 32 | 64, true) => format!("i{bits}"),
            (8 | 16 | 32 | 64, false) => format!("u{bits}"),
            _ => bail!("no FFI-safe Rust type for a {bits}-bit integer"),
        },
        Ty::Float { bits: 32 } => "f32".to_owned(),
        Ty::Float { bits: 64 } => "f64".to_owned(),
        Ty::Float { bits } => bail!("no Rust type for a {bits}-bit float"),
        Ty::Pointer {
            pointee,
            is_const,
            nullability,
            ..
        } => match pointee.resolved() {
            Ty::Function(sig) => {
                let f = fn_ty(sig, opaque)?;
                if *nullability == Nullability::NonNull {
                    f
                } else {
                    format!("Option<{f}>")
                }
            }
            Ty::Opaque { name, .. } => {
                opaque.insert(name.clone());
                format!(
                    "*{} {}",
                    if *is_const { "const" } else { "mut" },
                    ident(name)
                )
            }
            p => format!(
                "*{} {}",
                if *is_const { "const" } else { "mut" },
                rust_ty(p, opaque)?
            ),
        },
        Ty::Record { name } => ident(name),
        Ty::Opaque { name, .. } => {
            bail!("{name} is used by value but not defined by this interface")
        }
        Ty::Function(_) => bail!("a function type by value"),
        Ty::Array { elem, len } => format!("[{}; {len}]", rust_ty(elem, opaque)?),
    })
}

fn fn_ty(sig: &Signature, opaque: &mut BTreeSet<String>) -> Result<String> {
    let mut params = sig
        .params
        .iter()
        .map(|p| rust_ty(p, opaque))
        .collect::<Result<Vec<_>>>()?;
    if sig.variadic {
        params.push("...".to_owned());
    }
    let ret = match sig.ret.resolved() {
        Ty::Void => String::new(),
        _ => format!(" -> {}", rust_ty(&sig.ret, opaque)?),
    };
    Ok(format!(
        "unsafe extern \"C\" fn({}){ret}",
        params.join(", ")
    ))
}
