//! Host `intel_clc` (GPU laptop plan L3): the OpenCL-C -> NIR compiler iris' internal shaders need at build time (Mesa src/intel/shaders/meson.build), built from the same pinned Mesa checkout as the app-side Mesa, against the distro's LLVM/Clang/SPIRV-LLVM-Translator/libclc (deps.toml `llvm-dev`, `libclang-cpp`, `llvm-spirv-lib`, `libclc`).
//! It runs on the build host only, never enters an app process: the app-side Mesa is configured `intel-clc=system` and finds it through native.ini `[binaries] intel_clc` (mesa.rs `native_file`); mesa.rs `app_links` fails any app-side output that NEEDS libLLVM/libclang (owner D1).
//! Why a separate meson build: Mesa's own `intel-clc=enabled` path builds the tool with the device compilers and links it against LLVM, Clang and libclc, which the app-side build does not have (llvm_host builds only LLVM's static libs) and must not link.

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result};

/// `<mesa out>/intel-clc`: holds native.ini, logs and `build/`.
pub const SUBDIR: &str = "intel-clc";

/// The tool in the build dir (meson target path).
const TARGET: &str = "src/intel/compiler/intel_clc";

/// Project options: no platform, no driver, no API; only the intel compiler subtree `intel-clc=enabled` pulls in. Shared distro LLVM is fine here: the tool never ships.
pub const OPTIONS: &[(&str, &str)] = &[
    ("platforms", ""),
    ("gallium-drivers", ""),
    ("vulkan-drivers", ""),
    ("intel-clc", "enabled"),
    ("llvm", "enabled"),
    ("shared-llvm", "enabled"),
    ("glx", "disabled"),
    ("egl", "disabled"),
    ("gbm", "disabled"),
    ("opengl", "false"),
    ("gles1", "disabled"),
    ("gles2", "disabled"),
    ("valgrind", "disabled"),
    ("libunwind", "disabled"),
    ("build-tests", "false"),
];

/// Builds the tool into `<mesa_out>/intel-clc/build` from checkout `mesa` with the distro `llvm_config`; Ok(path) or Err(first error line + log path).
pub fn build(mesa_out: &Path, mesa: &Path, llvm_config: &str) -> Result<Result<PathBuf, String>> {
    let dir = mesa_out.join(SUBDIR);
    std::fs::create_dir_all(&dir)?;
    let ini = dir.join("native.ini");
    let text =
        format!("# generated by xtask (intel_clc.rs)\n[binaries]\nllvm-config = '{llvm_config}'\n");
    if std::fs::read_to_string(&ini).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(&ini, &text)?;
    }
    let build = dir.join("build");
    if !build.join("build.ninja").exists() {
        let log = dir.join("meson-setup.log");
        let status = Command::new("meson")
            .args(["setup", "--native-file"])
            .arg(&ini)
            .args(OPTIONS.iter().map(|(k, v)| format!("-D{k}={v}")))
            .arg(&build)
            .arg(mesa)
            .stdout(std::fs::File::create(&log)?)
            .stderr(std::fs::File::options().append(true).open(&log)?)
            .status()
            .context("running meson for intel_clc")?;
        if !status.success() {
            return Ok(Err(format!(
                "intel_clc: meson setup failed, see {}",
                log.display()
            )));
        }
    }
    let log = dir.join("ninja.log");
    let status = Command::new("ninja")
        .arg("-C")
        .arg(&build)
        .arg(TARGET)
        .stdout(std::fs::File::create(&log)?)
        .stderr(std::fs::File::options().append(true).open(&log)?)
        .status()
        .context("running ninja for intel_clc")?;
    if !status.success() {
        let text = std::fs::read_to_string(&log).unwrap_or_default();
        let first = text
            .lines()
            .find(|l| l.contains("error:") || l.starts_with("FAILED:"))
            .unwrap_or("ninja failed; its log names no error line");
        return Ok(Err(format!("intel_clc: {first} (log {})", log.display())));
    }
    Ok(Ok(build.join(TARGET)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn builds_only_the_compiler() {
        let get = |k: &str| OPTIONS.iter().find(|(n, _)| *n == k).map(|(_, v)| *v);
        assert_eq!(get("intel-clc"), Some("enabled"));
        assert_eq!(get("gallium-drivers"), Some(""));
        assert_eq!(get("vulkan-drivers"), Some(""));
        assert_eq!(get("platforms"), Some(""));
    }
}
