// SPDX-License-Identifier: MIT
//! SPDX gate: every file we author carries `SPDX-License-Identifier: MIT` near the top.

use std::path::Path;
use std::process::Command;

use anyhow::{Context, Result, bail};

const TAG: &str = "SPDX-License-Identifier:";
const OUR_LICENSE: &str = "MIT";

/// Lines searched for the tag: room for a shebang or a Markdown frontmatter opener before it.
const HEADER_LINES: usize = 3;

/// Files that cannot carry a comment, each with the reason.
const EXEMPT: &[(&str, &str)] = &[
    ("LICENSE", "the licence text itself"),
    (
        "Cargo.lock",
        "generated by cargo, which drops added comments",
    ),
];

pub fn check(root: &Path) -> Result<()> {
    let mut bad = Vec::new();
    let files = candidate_files(root)?;
    for rel in &files {
        if EXEMPT.iter().any(|(name, _)| rel == name) {
            continue;
        }
        let bytes = std::fs::read(root.join(rel)).with_context(|| format!("reading {rel}"))?;
        match header_license(&String::from_utf8_lossy(&bytes)) {
            Some(OUR_LICENSE) => {}
            Some(other) => bad.push(format!("{rel}: licence {other}, expected {OUR_LICENSE}")),
            None => bad.push(format!(
                "{rel}: no `{TAG}` in the first {HEADER_LINES} lines"
            )),
        }
    }
    if bad.is_empty() {
        eprintln!("spdx: {} files ok", files.len());
        return Ok(());
    }
    for line in &bad {
        eprintln!("spdx: {line}");
    }
    bail!(
        "{} of {} files lack a valid SPDX header",
        bad.len(),
        files.len()
    );
}

/// Tracked files plus new files not ignored -- what the next commit can contain.
fn candidate_files(root: &Path) -> Result<Vec<String>> {
    let out = Command::new("git")
        .args([
            "ls-files",
            "-z",
            "--cached",
            "--others",
            "--exclude-standard",
        ])
        .current_dir(root)
        .output()
        .context("running git ls-files")?;
    if !out.status.success() {
        bail!(
            "git ls-files failed: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
    let list = String::from_utf8(out.stdout).context("non-UTF-8 path in git ls-files")?;
    let mut files: Vec<String> = list
        .split('\0')
        .filter(|s| !s.is_empty())
        .map(String::from)
        .collect();
    // `--cached` still lists a tracked file deleted in the work tree
    files.retain(|f| root.join(f).is_file());
    Ok(files)
}

/// The licence expression of the first SPDX tag within `HEADER_LINES`, comment closers stripped.
fn header_license(text: &str) -> Option<&str> {
    text.lines().take(HEADER_LINES).find_map(|line| {
        let (_, rest) = line.split_once(TAG)?;
        let rest = rest.trim();
        let rest = rest
            .strip_suffix("-->")
            .or_else(|| rest.strip_suffix("*/"))
            .unwrap_or(rest);
        Some(rest.trim())
    })
}

#[cfg(test)]
mod tests {
    use super::header_license;

    #[test]
    fn comment_styles() {
        assert_eq!(
            header_license("// SPDX-License-Identifier: MIT\nfn main() {}"),
            Some("MIT")
        );
        assert_eq!(
            header_license("# SPDX-License-Identifier: MIT\n"),
            Some("MIT")
        );
        assert_eq!(
            header_license("<!-- SPDX-License-Identifier: MIT -->\n# Title"),
            Some("MIT")
        );
        assert_eq!(
            header_license("/* SPDX-License-Identifier: MIT */"),
            Some("MIT")
        );
    }

    #[test]
    fn after_shebang() {
        assert_eq!(
            header_license("#!/bin/sh\n# SPDX-License-Identifier: MIT\n"),
            Some("MIT")
        );
    }

    #[test]
    fn other_expression_is_returned_verbatim() {
        let text = "# SPDX-License-Identifier: GPL-2.0-or-later\n";
        assert_eq!(header_license(text), Some("GPL-2.0-or-later"));
        let text = "// SPDX-License-Identifier: MIT OR Apache-2.0\n";
        assert_eq!(header_license(text), Some("MIT OR Apache-2.0"));
    }

    #[test]
    fn tag_past_header_lines_is_missed() {
        // HEADER_LINES = 3: the tag on line 4 does not count
        assert_eq!(
            header_license("a\nb\nc\n// SPDX-License-Identifier: MIT\n"),
            None
        );
        assert_eq!(header_license(""), None);
    }
}
