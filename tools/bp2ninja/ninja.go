// globTree matches pattern (Soong glob: `*`, `?`, `**/`) below base; results are prefixed with dir.
func globTree(base, pattern, dir string) []string {
	var re strings.Builder
	re.WriteString("^")
	for i := 0; i < len(pattern); i++ {
		switch c := pattern[i]; {
		case strings.HasPrefix(pattern[i:], "**/"):
			re.WriteString("(?:.*/)?")
			i += 2
		case c == '*':
			re.WriteString("[^/]*")
		case c == '?':
			re.WriteString("[^/]")
		default:
			re.WriteString(regexp.QuoteMeta(string(c)))
		}
	}
	re.WriteString("$")
	rx := regexp.MustCompile(re.String())
	var out []string
	filepath.WalkDir(base, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		rel, _ := filepath.Rel(base, path)
		if rx.MatchString(rel) {
			out = append(out, filepath.Join(dir, rel))
		}
		return nil
	})
	return out
}

// Tools are the host programs the generated rules call.
type Tools struct{ CC, CXX, AR, Bison, Flex string }

func esc(s string) string {
	return strings.NewReplacer("$", "$$", " ", "$ ", ":", "$:", "\n", "$\n").Replace(s)
}

func join(list []string) string {
	out := make([]string, len(list))
	for i, s := range list {
		out[i] = esc(s)
	}
	return strings.Join(out, " ")
}

// shellQuote for flag values passed through a ninja variable into /bin/sh.
func shellQuote(list []string) string {
	out := make([]string, len(list))
	for i, s := range list {
		if strings.ContainsAny(s, " \"'$\\()<>&;|*?") {
			s = "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
		}
		out[i] = strings.ReplaceAll(s, "$", "$$")
	}
	return strings.Join(out, " ")
}

const header = `# Generated by bp2ninja; do not edit.
rule cc
  command = $cc -MD -MF $out.d $flags -c $in -o $out
  depfile = $out.d
  deps = gcc
  description = cc $in
rule ar
  command = rm -f $out && $ar crsD $out $in
  description = ar $out
rule link
  command = $cxx $mode -o $out $in $libs
  description = link $out
rule aidl
  command = $aidl --lang=cpp $flags -h $hdir -o $sdir $in
  description = aidl $in
rule protoc
  command = $aprotoc --cpp_out=$params:$outdir --dependency_out=$dep -I $base $flags $in
  depfile = $dep
  description = protoc $in
rule yacc
  command = $bison -d --defines=$hdr -o $src $in
  description = bison $in
rule lex
  command = $flex -o$out $in
  description = flex $in
rule genrule
  command = cd "$root" && /bin/bash $script
  description = genrule $name
  restat = 1
`

// emit writes the ninja file for every node.
func (g *Graph) emit(tools Tools) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%sar = %s\ncxx = %s\nbison = %s\nflex = %s\nroot = %s\n\n", header, esc(tools.AR), esc(tools.CXX), esc(tools.Bison), esc(tools.Flex), esc(g.tree))
	// paths first: links need their dependencies' outputs
	for _, n := range g.order {
		base := filepath.Join(g.out, n.side.String(), n.name)
		switch n.kind {
		case Static:
			n.out = filepath.Join(base, n.name+".a")
		case Shared:
			n.out = filepath.Join(base, n.name+".so")
		case Binary:
			n.out = filepath.Join(base, n.name)
		}
	}
	// genrules: tools' paths are known now
	for _, n := range g.order {
		if n.kind == Gen {
			g.emitGen(&b, n)
		}
	}
	for _, n := range g.order {
		for _, e := range n.edges {
			g.emitEdge(&b, e)
		}
	}
	for _, n := range g.order {
		if n.kind == Headers || n.kind == Gen {
			continue
		}
		flags := g.compileFlags(n)
		var waits []string
		genClosure(n, map[*Node]bool{}, &waits)
		for _, s := range n.srcs {
			src := s
			if !filepath.IsAbs(src) {
				src = g.abs(s)
			}
			rel := strings.TrimPrefix(strings.TrimPrefix(src, g.tree+"/"), g.out+"/")
			obj := filepath.Join(g.out, "obj", n.side.String(), n.name, n.kind.String(), rel+".o")
			lang := flags.cxx
			cc := tools.CXX
			switch filepath.Ext(s) {
			case ".c":
				lang, cc = flags.c, tools.CC
			case ".S", ".s":
				lang, cc = flags.asm, tools.CC
			}
			fmt.Fprintf(&b, "build %s: cc %s || %s\n  cc = %s\n  flags = %s\n", esc(obj), esc(src), join(waits), esc(cc), shellQuote(lang))
			n.objs = append(n.objs, obj)
		}
		switch n.kind {
		case Static:
			fmt.Fprintf(&b, "build %s: ar %s\n", esc(n.out), join(n.objs))
		case Shared, Binary:
			libs, inputs := g.linkLibs(n)
			mode := "-Wl,--no-undefined"
			if n.kind == Shared {
				mode = "-shared -Wl,-soname," + n.name + ".so -Wl,--no-undefined"
			}
			fmt.Fprintf(&b, "build %s: link %s | %s\n  mode = %s\n  libs = %s\n", esc(n.out), join(n.objs), join(inputs), mode, shellQuote(libs))
		}
	}
	var defaults []string
	for _, n := range g.order {
		if n.out != "" {
			defaults = append(defaults, n.out)
		}
	}
	fmt.Fprintf(&b, "\ndefault %s\n", join(defaults))
	return b.String()
}

type langFlags struct{ c, cxx, asm []string }

// compileFlags: Soong's language defaults (read from its global.go), the module's flags, then include
// paths in Soong's order (local, global, own exports, dependencies' exports, Soong's global includes).
// -Wno-error: distro clang warns differently from AOSP's clang; errors are what this build measures.
// libc++: AOSP's C++ assumes it (libstdc++ 14 rejects libbase's non-const set comparator).
func (g *Graph) compileFlags(n *Node) langFlags {
	p := n.props
	common := []string{"-fPIC", "-O2", "-w"}
	common = append(common, p.strs("cflags")...)
	common = append(common, n.genCflags...)
	common = append(common, "-Wno-error")
	var inc []string
	for _, d := range p.strs("local_include_dirs") {
		inc = append(inc, "-I"+g.abs(filepath.Join(n.mod.Dir, d)))
	}
	for _, d := range p.strs("include_dirs") {
		inc = append(inc, "-I"+g.abs(d))
	}
	inc = append(inc, "-I"+g.abs(n.mod.Dir))
	inc = append(inc, n.exports...)
	inc = append(inc, n.genIncs...)
	for _, d := range append(append(append(append([]*Node{}, n.deps.headers...), n.deps.static...), n.deps.shared...), n.deps.whole...) {
		inc = append(inc, d.exports...)
	}
	for _, d := range g.soong.GlobalIncludes {
		inc = append(inc, "-I"+g.abs(d))
	}
	inc = dedup(inc)
	cstd := p.str("c_std")
	if cstd == "" || cstd == "experimental" {
		cstd = g.soong.CStd
	}
	cppstd := p.str("cpp_std")
	if cppstd == "" || cppstd == "experimental" {
		cppstd = g.soong.CppStd
	}
	cxx := append(append([]string{"-std=" + cppstd, "-stdlib=libc++"}, common...), p.strs("cppflags")...)
	if n.side == Device {
		cxx = append(cxx, "-I"+filepath.Join(g.out, "compat", "cxx"))
	}
	if !p.boolean("rtti", false) {
		cxx = append(cxx, "-fno-rtti")
	}
	c := append(append([]string{"-std=" + cstd}, common...), p.strs("conlyflags")...)
	asm := append(append([]string{}, common...), p.strs("asflags")...)
	return langFlags{append(c, inc...), append(cxx, inc...), append(asm, inc...)}
}

// linkLibs: whole archives, the static closure, shared libraries (also those static dependencies
// need), and the glibc system libraries bionic folds into libc.
func (g *Graph) linkLibs(n *Node) (libs, inputs []string) {
	var closure []*Node
	staticClosure(n, map[*Node]bool{}, &closure)
	whole := map[*Node]bool{}
	for _, d := range n.deps.whole {
		whole[d] = true
	}
	shared := map[*Node]bool{}
	var sharedOrder []*Node
	addShared := func(list []*Node) {
		for _, d := range list {
			if !shared[d] {
				shared[d] = true
				sharedOrder = append(sharedOrder, d)
			}
		}
	}
	addShared(n.deps.shared)
	if len(n.deps.whole) > 0 {
		libs = append(libs, "-Wl,--whole-archive")
		for _, d := range n.deps.whole {
			libs = append(libs, d.out)
			inputs = append(inputs, d.out)
		}
		libs = append(libs, "-Wl,--no-whole-archive")
	}
	libs = append(libs, "-Wl,--start-group")
	for _, d := range closure {
		addShared(d.deps.shared)
		if !whole[d] && d.kind == Static {
			libs = append(libs, d.out)
			inputs = append(inputs, d.out)
		}
	}
	libs = append(libs, "-Wl,--end-group")
	for _, d := range sharedOrder {
		if d.kind == Shared {
			// absolute build-tree rpath: build tools (aidl) run from here; installed runtime
			// libraries get their search path from the install layout, not from this
			libs = append(libs, d.out, "-Wl,-rpath,"+filepath.Dir(d.out))
			inputs = append(inputs, d.out)
		}
	}
	libs = append(libs, "-stdlib=libc++", "-lpthread", "-ldl", "-lrt", "-lm")
	return libs, inputs
}
