// Sharded javac (base.go compile, enableSharding): a device module with Turbine on and javac_shard_size > 0 compiles its .java sources in
// chunks of javac_shard_size and its srcjars in chunks of javac_shard_size/5 ("approximately 5 sources per srcjar"), one javac each, every
// shard against the module's own local header jars (turbine) ahead of its classpath, so sources in other shards resolve and turbine breaks
// intra-module cycles. Each shard's classes are repackaged on their own (repackageFlagsIfNecessary "javac-<i>") and merged with the static
// libraries into the implementation jar as before. An edit that leaves turbine's bytes alone (method body) reruns only its shard's javac.
// Annotation processors run per shard as in Soong: the framework's ChangeId and UnsupportedAppUsage write one resource per (package,
// top-level class) and SystemFeaturesMetadata reads only PackageManager's fields, so the shards' outputs are disjoint and merge to the
// unsharded set. Not byte-equal to one javac: .uau rows name the shard's srcjar directory, and a constant another processing unit generates
// is read with getstatic instead of inlined (PackageManager.SDK_FEATURE_COUNT, re-declared upstream for exactly that case).

// javacShardSize: javac_shard_size, 0 = unsharded.
func javacShardSize(n *jNode) int {
	if v, ok := n.props.get("javac_shard_size").(int64); ok && v > 0 {
		return int(v)
	}
	return 0
}

// shardPaths is android.ShardPaths: consecutive chunks of at most size, in order. A size below 1 counts as 1 (Soong would divide by zero
// for javac_shard_size < 5 with srcjars).
func shardPaths(paths []string, size int) [][]string {
	size = max(size, 1)
	var out [][]string
	for len(paths) > 0 {
		k := min(size, len(paths))
		out = append(out, paths[:k:k])
		paths = paths[k:]
	}
	return out
}

// javacShards emits the shards' javac edges (compileJavaClasses with idx: javac/<stem><i>.jar, working directories suffixed <i>) and
// returns their repackaged class jars, source shards first, then srcjar shards.
func (g *Graph) javacShards(n *jNode, size int, localHdr, java, srcjars, waits, flags []string, ver javaVersion, d javaDeps, repackage, jar string) []string {
	d.classpath = append(slices.Clone(localHdr), d.classpath...)
	stem := strings.TrimSuffix(jar, filepath.Ext(jar))
	var jars []string
	compile := func(i int, java, srcjars []string) {
		idx := strconv.Itoa(i)
		out := filepath.Join(n.dir, "javac", stem+idx+filepath.Ext(jar))
		g.javacIn(n, out, idx, java, srcjars, waits, flags, ver, d)
		jars = append(jars, g.repackage(n, out, repackage, "javac-"+idx, jar))
	}
	for _, s := range shardPaths(java, size) {
		compile(len(jars), s, nil)
	}
	for _, s := range shardPaths(srcjars, size/5) {
		compile(len(jars), nil, s)
	}
	return jars
}

// Pieces: a departure from Soong, which runs jarjar and d8 once over a module's whole combined implementation jar (base.go jarjarIfNecessary,
// dex.go compileDex; no intermediate dexing). Measured on framework-minus-apex: after a method-body edit those two steps (~9 s + ~22 s) cost
// more than the one shard's javac. So a sharded module's implementation is cut into pieces: each javac shard, then "rest" = the other
// implementation jars (static libs, kotlin, extra jars) combined, minus every class a shard defines -- the combined jar keeps the first copy
// of a duplicate and the shards come first (framework: 368 static AIDL classes also generated by its srcjar shards). jarjar_rules rename
// per class (no keep rules), so each piece goes through jarjar alone and the implementation jar is their merge; d8 compiles each piece with
// --intermediate and one d8 merges the dex archives. An edit then reruns its shard's chain and the merges.

// shardPieces returns the pieces in implementation order, through jarjar_rules when the module has them (rest in jarjar_shards runs).
func (g *Graph) shardPieces(n *jNode, shardJars, implJars []string, rules string, jjShards int, jar string) []string {
	pieces := slices.Clone(shardJars)
	var rest []string
	for _, x := range implJars {
		if !slices.Contains(shardJars, x) {
			rest = append(rest, x)
		}
	}
	if len(rest) > 0 {
		rc := rest[0]
		if len(rest) > 1 {
			rc = filepath.Join(n.dir, "pieces", "rest-combined", jar)
			g.java.combine(rc, rest, "")
		}
		rf := filepath.Join(n.dir, "pieces", "rest", jar)
		g.java.edge("unshadow", []string{rf}, []string{rc}, shardJars, nil, [][2]string{{"shadows", join(shardJars)}})
		pieces = append(pieces, rf)
	}
	if rules == "" {
		return pieces
	}
	for i, p := range pieces {
		name, k := strconv.Itoa(i), 1
		if i == len(shardJars) {
			name, k = "rest", jjShards
		}
		jj := filepath.Join(n.dir, "jarjar", name, jar)
		g.jarjar(n, jj, p, rules, k)
		pieces[i] = jj
	}
	return pieces
}

// dexPieces: d8 --intermediate per piece into dex-pieces/<i>.zip, then d8 over those archives with the module's flags into dex, resources
// from the implementation jar as the unsharded d8 rule.
func (g *Graph) dexPieces(n *jNode, dex string, pieces, flags, libs []string, zipFlags, d8 string) {
	implicit := append(slices.Clone(libs), d8)
	var outs []string
	for i, p := range pieces {
		o := filepath.Join(n.dir, "dex-pieces", strconv.Itoa(i)+".zip")
		g.java.edge("d8piece", []string{o}, []string{p}, implicit, nil, [][2]string{{"flags", ninjaRaw(flags)}, {"d8", esc(d8)}})
		outs = append(outs, o)
	}
	g.java.edge("d8merge", []string{dex}, outs, append(implicit, n.implRes), nil, [][2]string{
		{"flags", ninjaRaw(flags)}, {"outdir", esc(filepath.Dir(dex))}, {"zipflags", zipFlags}, {"d8", esc(d8)}, {"resjar", esc(n.implRes)},
	})
}

// shardRules: unshadow drops from $in the classes the $shards define (zip2zip -x per name; names hold no glob characters, set -f keeps the
// shell from expanding them); d8piece and d8merge are the d8 rule split in two. All three commit only changed bytes and restat, so an edit that
// leaves a piece's classes alone stops there.
func (j *javaGraph) shardRules() string {
	d8 := "PATH=$jdk/bin:$$PATH $d8 " + strings.Join(j.cfg.D8Flags, " ") + " $flags"
	return "rule unshadow\n  command = set -f && export LC_ALL=C && unzip -Z1 $in | grep '\\.class$$' | sort > $out.own; (for j in $shadows; do unzip -Z1 $$j; done) | grep '\\.class$$' | sort -u | comm -12 $out.own - > $out.drop && rm -f $out.tmp && $zip2zip -i $in -o $out.tmp $$(sed 's/^/-x /' $out.drop) && rm -f $out.own $out.drop && " + commitIfChanged +
		"\n  restat = 1\n  description = unshadow $out\n" +
		"rule d8piece\n  command = rm -f $out.tmp.zip && " + d8 + " --intermediate --output $out.tmp.zip --no-dex-input-jar $in && (if cmp -s $out.tmp.zip $out; then rm $out.tmp.zip; else mv $out.tmp.zip $out; fi)\n  restat = 1\n  description = d8 piece $out\n" +
		"rule d8merge\n  command = rm -rf $outdir && mkdir -p $outdir && " + d8 + " --output $outdir $in && $soongzip $zipflags -o $outdir/classes.dex.jar -C $outdir -f \"$outdir/classes*.dex\" && $mergezips -D -stripFile \"**/*.class\" $out.tmp $outdir/classes.dex.jar $resjar && rm -f $outdir/classes*.dex $outdir/classes.dex.jar && " + commitIfChanged + "\n  restat = 1\n  description = d8 merge $out\n"
}
