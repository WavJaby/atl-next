// buildPropFile: the generated build.prop under -out, written whenever a release config is given (-release). The property service (crate atl-property-service) loads it.
const buildPropFile = "gen/build.prop"

// buildProp: the properties AOSP's build.prop takes from the release config and the tree, in build.prop format (`name=value` lines, `#` comments), as gen_build_prop.py prints them.
//   - ro.build.id: build/make/core/build_id.mk BUILD_ID (version_util.mk; gen_build_prop.py `ro.build.id?=`; init's fingerprint takes it).
//   - ro.build.version.*: gen_build_prop.py lines 200-212 from Soong's product variables, which build/make/core/version_util.mk + soong_config.mk derive from release flags:
//     sdk = RELEASE_PLATFORM_SDK_VERSION; sdk_full = RELEASE_PLATFORM_SDK_VERSION_FULL, else "<sdk>.0", its major must equal sdk; preview_sdk = 0 when the codename is REL, else 1;
//     codename = RELEASE_PLATFORM_VERSION_CODENAME; all_codenames = RELEASE_PLATFORM_VERSION_ALL_CODENAMES as a list (add_json_csv: split on commas and blanks) joined by ","; known_codenames = RELEASE_PLATFORM_VERSION_KNOWN_CODENAMES;
//     release = RELEASE_PLATFORM_VERSION_LAST_STABLE; release_or_codename = PLATFORM_VERSION (last stable when REL, else the codename); release_or_preview_display = PLATFORM_DISPLAY_VERSION, which defaults to PLATFORM_VERSION; security_patch = RELEASE_PLATFORM_SECURITY_PATCH.
//   - Not written: preview_sdk_fingerprint (an md5 over the API files, not a release flag) and base_os (PRODUCT_BASE_OS, product config; empty without one, the same as unset to Build.VERSION.BASE_OS).
func buildProp(r *Release, buildID string) (string, error) {
	field := func(name string) string { return strings.Join(strings.Fields(r.Flag(name)), " ") }
	sdk := field("RELEASE_PLATFORM_SDK_VERSION")
	sdkFull := field("RELEASE_PLATFORM_SDK_VERSION_FULL")
	if sdkFull == "" {
		sdkFull = sdk + ".0"
	} else if major, _, _ := strings.Cut(sdkFull, "."); major != sdk {
		return "", fmt.Errorf("release %s: RELEASE_PLATFORM_SDK_VERSION_FULL %s: its major version must match RELEASE_PLATFORM_SDK_VERSION %s (version_util.mk)", r.Name, sdkFull, sdk)
	}
	codename := field("RELEASE_PLATFORM_VERSION_CODENAME")
	lastStable := field("RELEASE_PLATFORM_VERSION_LAST_STABLE")
	version, preview := codename, "1"
	if codename == "REL" {
		version, preview = lastStable, "0"
	}
	all := strings.FieldsFunc(r.Flag("RELEASE_PLATFORM_VERSION_ALL_CODENAMES"), func(c rune) bool {
		return c == ',' || c == ' ' || c == '\t' || c == '\n'
	})
	props := [][2]string{
		{"ro.build.id", buildID},
		{"ro.build.version.sdk", sdk},
		{"ro.build.version.sdk_full", sdkFull},
		{"ro.build.version.preview_sdk", preview},
		{"ro.build.version.codename", codename},
		{"ro.build.version.all_codenames", strings.Join(all, ",")},
		{"ro.build.version.known_codenames", field("RELEASE_PLATFORM_VERSION_KNOWN_CODENAMES")},
		{"ro.build.version.release", lastStable},
		{"ro.build.version.release_or_codename", version},
		{"ro.build.version.release_or_preview_display", version},
		{"ro.build.version.security_patch", field("RELEASE_PLATFORM_SECURITY_PATCH")},
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by bp2ninja from build/release (release config %s) and build/make/core/build_id.mk, do not edit\n", r.Name)
	for _, p := range props {
		if p[1] == "" {
			return "", fmt.Errorf("release %s: %s would be empty", r.Name, p[0])
		}
		fmt.Fprintf(&b, "%s=%s\n", p[0], p[1])
	}
	return b.String(), nil
}

// readBuildID: BUILD_ID of build/make/core/build_id.mk, the one assignment it holds.
func readBuildID(tree string) (string, error) {
	path := filepath.Join(tree, "build/make/core/build_id.mk")
	text, err := readFile(path)
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(text), "\n") {
		if id, ok := strings.CutPrefix(strings.TrimSpace(line), "BUILD_ID="); ok && id != "" {
			return id, nil
		}
	}
	return "", fmt.Errorf("%s: no BUILD_ID=", path)
}
