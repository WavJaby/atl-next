// Expected lines follow build/make/core/version_util.mk and gen_build_prop.py by hand: the fixture flags are bp2a's (REL) and a preview config's.

func release(flags map[string]string) *Release {
	base := map[string]string{
		"RELEASE_PLATFORM_SDK_VERSION":             "36",
		"RELEASE_PLATFORM_SDK_VERSION_FULL":        "",
		"RELEASE_PLATFORM_VERSION_CODENAME":        "REL",
		"RELEASE_PLATFORM_VERSION_ALL_CODENAMES":   "REL",
		"RELEASE_PLATFORM_VERSION_KNOWN_CODENAMES": "Base,Baklava",
		"RELEASE_PLATFORM_VERSION_LAST_STABLE":     "16",
		"RELEASE_PLATFORM_SECURITY_PATCH":          "2025-06-05",
	}
	for k, v := range flags {
		base[k] = v
	}
	return &Release{Name: "t", flags: base}
}

func TestBuildPropFinal(t *testing.T) {
	got, err := buildProp(release(nil), "BP2A.1")
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"ro.build.id=BP2A.1",
		"ro.build.version.sdk=36",
		// unset SDK_VERSION_FULL: "<sdk>.0"
		"ro.build.version.sdk_full=36.0",
		// REL: PLATFORM_PREVIEW_SDK_VERSION 0
		"ro.build.version.preview_sdk=0",
		"ro.build.version.codename=REL",
		"ro.build.version.all_codenames=REL",
		"ro.build.version.known_codenames=Base,Baklava",
		"ro.build.version.release=16",
		// REL: PLATFORM_VERSION = last stable; DISPLAY defaults to it
		"ro.build.version.release_or_codename=16",
		"ro.build.version.release_or_preview_display=16",
		"ro.build.version.security_patch=2025-06-05",
	}
	lines := strings.Split(strings.TrimSpace(got), "\n")
	if !strings.HasPrefix(lines[0], "# generated by bp2ninja") {
		t.Errorf("header %q", lines[0])
	}
	if strings.Join(lines[1:], "\n") != strings.Join(want, "\n") {
		t.Errorf("got\n%s\nwant\n%s", strings.Join(lines[1:], "\n"), strings.Join(want, "\n"))
	}
}

func TestBuildPropPreview(t *testing.T) {
	got, err := buildProp(release(map[string]string{
		"RELEASE_PLATFORM_VERSION_CODENAME":      "Baklava",
		"RELEASE_PLATFORM_VERSION_ALL_CODENAMES": "VanillaIceCream, Baklava",
		"RELEASE_PLATFORM_SDK_VERSION_FULL":      "36.1",
	}), "X")
	if err != nil {
		t.Fatal(err)
	}
	for _, line := range []string{
		"ro.build.version.sdk_full=36.1",
		// not REL: preview 1, PLATFORM_VERSION = the codename
		"ro.build.version.preview_sdk=1",
		"ro.build.version.release_or_codename=Baklava",
		"ro.build.version.release_or_preview_display=Baklava",
		// add_json_csv splits on commas and blanks
		"ro.build.version.all_codenames=VanillaIceCream,Baklava",
	} {
		if !strings.Contains(got, "\n"+line+"\n") {
			t.Errorf("missing %q in\n%s", line, got)
		}
	}
	// version_util.mk: SDK_VERSION_FULL's major must equal SDK_VERSION
	if _, err := buildProp(release(map[string]string{"RELEASE_PLATFORM_SDK_VERSION_FULL": "35.1"}), "X"); err == nil {
		t.Error("a mismatched SDK_VERSION_FULL must fail")
	}
	if _, err := buildProp(release(map[string]string{"RELEASE_PLATFORM_SECURITY_PATCH": ""}), "X"); err == nil {
		t.Error("an empty value must fail")
	}
}

func TestReadBuildID(t *testing.T) {
	tree := t.TempDir()
	p := filepath.Join(tree, "build/make/core/build_id.mk")
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte("# comment\nBUILD_ID=BP2A.250605.031.A2\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if id, err := readBuildID(tree); err != nil || id != "BP2A.250605.031.A2" {
		t.Errorf("%q %v", id, err)
	}
	if err := os.WriteFile(p, []byte("# none\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := readBuildID(tree); err == nil {
		t.Error("no BUILD_ID must fail")
	}
}
