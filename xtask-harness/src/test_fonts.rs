//! The pinned test font set and the fontconfig config that makes atld's desktop fonts deterministic: a generated `fonts.conf` with one `<dir>`, its own `<cachedir>` and explicit `<alias>` prefers, no `<include>`, so no distro `conf.d` rule (aliases, synthetic emboldening, lang rules) applies.
//! Set: AOSP's Roboto (variable wght/ital/wdth, external/roboto-fonts) for sans-serif, AOSP's DroidSansMono for monospace; both Apache-2.0 (their Soong packages), never shipped.
//! serif, cursive and courier (serif-monospace's query) are aliased to fonts the rows reject (fonts.toml `differs`), so those families emit nothing instead of whatever fontconfig ranks first.
//! [`advance`] is the runtime font gate's independent expectation: hmtx advances summed at the default instance, read here with read-fonts, not through atld or Android.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, ensure};
use atl_layout::Layout;

use crate::tree;

/// (tree dir, file, fontconfig family) of the test fonts.
pub const ROBOTO: (&str, &str, &str) = ("external/roboto-fonts", "Roboto-Regular.ttf", "Roboto");
pub const MONO: (&str, &str, &str) = (
    "frameworks/base/data/fonts",
    "DroidSansMono.ttf",
    "Droid Sans Mono",
);
/// atld's `--font-data`: AOSP's alias.json and fallback_order.json.
const FONT_DATA: &str = "frameworks/base/data/fonts";

/// A staged set: the conf for FONTCONFIG_FILE and the font files it lists.
pub struct TestFonts {
    pub conf: PathBuf,
    pub files: Vec<PathBuf>,
    pub font_data: PathBuf,
}

/// The pinned file of a font.
pub fn file(layout: &Layout, font: (&str, &str, &str)) -> PathBuf {
    tree::shared_tree(layout).join(font.0).join(font.1)
}

/// Copies the set into `<dir>/files` and writes `<dir>/fonts.conf` preferring `sans` for sans-serif (the deliberate break passes the mono family).
pub fn stage(layout: &Layout, dir: &Path, sans: &str) -> Result<TestFonts> {
    let files_dir = dir.join("files");
    if files_dir.exists() {
        std::fs::remove_dir_all(&files_dir)?;
    }
    std::fs::create_dir_all(&files_dir)?;
    let mut files = Vec::new();
    for f in [ROBOTO, MONO] {
        let src = file(layout, f);
        ensure!(src.is_file(), "missing input {}", src.display());
        let to = files_dir.join(f.1);
        std::fs::copy(&src, &to).with_context(|| src.display().to_string())?;
        files.push(to);
    }
    let alias = |generic: &str, family: &str| {
        format!(
            "  <alias binding=\"strong\"><family>{generic}</family><prefer><family>{family}</family></prefer></alias>\n"
        )
    };
    let conf = format!(
        "<?xml version=\"1.0\"?>\n<!DOCTYPE fontconfig SYSTEM \"urn:fontconfig:fonts.dtd\">\n<!-- generated by xtask test_fonts.rs, do not edit -->\n<fontconfig>\n  <dir>{}</dir>\n  <cachedir>{}</cachedir>\n{}{}{}{}{}</fontconfig>\n",
        files_dir.display(),
        dir.join("cache").display(),
        alias("sans-serif", sans),
        alias("monospace", MONO.2),
        alias("serif", sans),
        alias("cursive", sans),
        alias("courier", MONO.2),
    );
    let conf_path = dir.join("fonts.conf");
    std::fs::write(&conf_path, conf)?;
    Ok(TestFonts {
        conf: conf_path,
        files,
        font_data: tree::shared_tree(layout).join(FONT_DATA),
    })
}

/// `text`'s advance at text size = unitsPerEm, so each glyph's hmtx advance is an integer number of pixels and no rounding mode matters: (sum, unitsPerEm). Default instance (no variation coordinates), one glyph per char, no kerning (the fixture turns `kern` and `liga` off).
pub fn advance(font: &Path, text: &str) -> Result<(u32, u16)> {
    let data = std::fs::read(font).with_context(|| font.display().to_string())?;
    use read_fonts::TableProvider;
    let bad = |e: read_fonts::ReadError| anyhow::anyhow!("{}: {e}", font.display());
    let face = read_fonts::FontRef::new(&data).map_err(bad)?;
    let (cmap, hmtx) = (face.cmap().map_err(bad)?, face.hmtx().map_err(bad)?);
    let mut sum = 0u32;
    for c in text.chars() {
        let g = cmap
            .map_codepoint(c)
            .with_context(|| format!("{}: no glyph for {c:?}", font.display()))?;
        // Hmtx::advance: the unvaried advance, the last long metric repeated past numberOfHMetrics
        sum += u32::from(
            hmtx.advance(g)
                .with_context(|| format!("{}: no advance for {c:?}", font.display()))?,
        );
    }
    Ok((sum, face.head().map_err(bad)?.units_per_em()))
}
